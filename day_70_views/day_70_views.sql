-- ============================================================================
-- 13. INSTEAD OF TRIGGER
-- ============================================================================

-- Demonstrates custom write behavior for a more complex view.

CREATE VIEW employee_department_edit AS
SELECT
    e.employee_id,
    e.employee_name,
    d.department_id,
    d.department_name
FROM employees e
JOIN departments d
    ON e.department_id = d.department_id;


CREATE FUNCTION update_employee_department_view()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN

        IF NEW.employee_name IS NULL
           OR LENGTH(TRIM(NEW.employee_name)) = 0 THEN
            RAISE EXCEPTION 'Employee name cannot be empty';
        END IF;

        UPDATE employees
        SET
            employee_name = NEW.employee_name,
            department_id = NEW.department_id
        WHERE employee_id = OLD.employee_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Employee % does not exist',
                OLD.employee_id;
        END IF;

        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'Unsupported operation: %', TG_OP;
END;
$$;


CREATE TRIGGER trg_employee_department_view_update
INSTEAD OF UPDATE
ON employee_department_edit
FOR EACH ROW
EXECUTE FUNCTION update_employee_department_view();


-- ============================================================================
-- 14. PARAMETERIZED FUNCTION CONSUMING A VIEW
-- ============================================================================

-- Views do not accept parameters.
-- The consuming function supplies dynamic filtering.

CREATE FUNCTION get_employees_by_department(
    p_department_id INTEGER,
    p_minimum_salary NUMERIC DEFAULT 0
)
RETURNS TABLE (
    employee_id INTEGER,
    employee_name VARCHAR,
    salary NUMERIC,
    department_id INTEGER
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_department_id <= 0 THEN
        RAISE EXCEPTION 'Department identifier must be positive';
    END IF;

    IF p_minimum_salary < 0 THEN
        RAISE EXCEPTION 'Minimum salary cannot be negative';
    END IF;

    RETURN QUERY
    SELECT
        e.employee_id,
        e.employee_name,
        e.salary,
        e.department_id
    FROM employee_edit_view e
    WHERE e.department_id = p_department_id
      AND e.salary >= p_minimum_salary
      AND e.is_active = TRUE
    ORDER BY e.salary DESC;
END;
$$;


-- ============================================================================
-- 15. REUSABLE AGGREGATION FUNCTION
-- ============================================================================

CREATE FUNCTION get_department_payroll(
    p_department_id INTEGER
)
RETURNS NUMERIC
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(
        SUM(salary),
        0
    )
    FROM employee_edit_view
    WHERE department_id = p_department_id
      AND is_active = TRUE;
$$;


-- ============================================================================
-- 16. MATERIALIZED VIEW
-- ============================================================================

-- Unlike a regular view, the result is physically stored.
-- Changes in base tables are not reflected until REFRESH MATERIALIZED VIEW.

CREATE MATERIALIZED VIEW department_statistics_cache AS
SELECT
    department_id,
    department_name,
    employee_count,
    average_salary,
    total_payroll
FROM department_statistics
WITH DATA;


CREATE UNIQUE INDEX idx_department_statistics_cache
    ON department_statistics_cache(department_id);


-- ============================================================================
-- 17. STORED PROCEDURE FOR REFRESH
-- ============================================================================

CREATE PROCEDURE refresh_department_statistics()
LANGUAGE plpgsql
AS $$
BEGIN
    REFRESH MATERIALIZED VIEW department_statistics_cache;
END;
$$;


-- ============================================================================
-- 18. VIEW DEPENDENCY INSPECTION
-- ============================================================================

CREATE VIEW view_dependency_report AS
SELECT
    dependent_ns.nspname AS dependent_schema,
    dependent_view.relname AS dependent_view,
    source_ns.nspname AS source_schema,
    source_table.relname AS source_relation
FROM pg_rewrite rw
JOIN pg_class dependent_view
    ON dependent_view.oid = rw.ev_class
JOIN pg_namespace dependent_ns
    ON dependent_ns.oid = dependent_view.relnamespace
JOIN pg_depend dep
    ON dep.objid = rw.oid
JOIN pg_class source_table
    ON source_table.oid = dep.refobjid
JOIN pg_namespace source_ns
    ON source_ns.oid = source_table.relnamespace
WHERE dependent_ns.nspname = 'view_lab'
  AND dependent_view.relkind = 'v'
  AND source_table.oid <> dependent_view.oid;


