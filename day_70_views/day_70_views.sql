-- ============================================================================
-- 5. SIMPLE VIEW
-- ============================================================================

-- Exposes selected columns and filters inactive employees.
-- This separates the consumer interface from the underlying table.

CREATE VIEW employee_directory AS
SELECT
    employee_id,
    employee_name,
    department_id
FROM employees
WHERE is_active = TRUE;


COMMENT ON VIEW employee_directory IS
'Public employee directory excluding inactive employees.';


-- ============================================================================
-- 6. JOIN VIEW
-- ============================================================================

-- Combines employee and department information.

CREATE VIEW employee_department_details AS
SELECT
    e.employee_id,
    e.employee_name,
    d.department_id,
    d.department_name,
    d.location,
    e.hired_at
FROM employees e
INNER JOIN departments d
    ON e.department_id = d.department_id
WHERE e.is_active = TRUE;


-- ============================================================================
-- 7. AGGREGATE VIEW
-- ============================================================================

-- LEFT JOIN preserves departments with zero active employees.

CREATE VIEW department_statistics AS
SELECT
    d.department_id,
    d.department_name,
    COUNT(e.employee_id) AS employee_count,
    COALESCE(ROUND(AVG(e.salary), 2), 0) AS average_salary,
    COALESCE(SUM(e.salary), 0) AS total_payroll,
    MIN(e.salary) AS minimum_salary,
    MAX(e.salary) AS maximum_salary
FROM departments d
LEFT JOIN employees e
    ON d.department_id = e.department_id
    AND e.is_active = TRUE
GROUP BY
    d.department_id,
    d.department_name;


COMMENT ON VIEW department_statistics IS
'Department-level employee and payroll aggregation.';


-- ============================================================================
-- 8. COMPLEX JOIN AND AGGREGATION VIEW
-- ============================================================================

CREATE VIEW project_workload AS
SELECT
    p.project_id,
    p.project_name,
    d.department_name,
    p.project_status,
    p.budget,
    COUNT(a.assignment_id) AS assignment_count,
    COALESCE(SUM(a.allocated_hours), 0) AS total_allocated_hours,
    COUNT(DISTINCT a.employee_id) AS assigned_employee_count
FROM projects p
INNER JOIN departments d
    ON p.department_id = d.department_id
LEFT JOIN assignments a
    ON p.project_id = a.project_id
GROUP BY
    p.project_id,
    p.project_name,
    d.department_name,
    p.project_status,
    p.budget;


-- ============================================================================
-- 9. NESTED VIEW
-- ============================================================================

-- Reuses project_workload rather than repeating its joins and aggregation.

CREATE VIEW high_workload_projects AS
SELECT
    project_id,
    project_name,
    department_name,
    total_allocated_hours,
    assigned_employee_count,
    budget
FROM project_workload
WHERE total_allocated_hours > 100;


-- ============================================================================
-- 10. FILTERED REPORTING VIEW
