CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT department_name_not_empty
        CHECK (LENGTH(TRIM(department_name)) > 0)
);


CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(120) NOT NULL,
    department_id INTEGER NOT NULL,
    salary NUMERIC(12, 2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    hired_at DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT employee_salary_nonnegative
        CHECK (salary >= 0),

    CONSTRAINT employee_name_not_empty
        CHECK (LENGTH(TRIM(employee_name)) > 0),

    CONSTRAINT employee_department_fk
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);


CREATE TABLE projects (
    project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(150) NOT NULL UNIQUE,
    department_id INTEGER NOT NULL,
    budget NUMERIC(14, 2) NOT NULL,
    project_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT project_budget_nonnegative
        CHECK (budget >= 0),

    CONSTRAINT project_status_valid
        CHECK (
            project_status IN (
                'ACTIVE',
                'COMPLETED',
                'ON_HOLD',
                'CANCELLED'
            )
        ),

    CONSTRAINT project_department_fk
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id)
        ON DELETE RESTRICT
);


CREATE TABLE assignments (
    assignment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    allocated_hours NUMERIC(10, 2) NOT NULL,

    CONSTRAINT assignment_hours_nonnegative
        CHECK (allocated_hours >= 0),

    CONSTRAINT assignment_employee_fk
        FOREIGN KEY (employee_id)
        REFERENCES employees(employee_id)
        ON DELETE CASCADE,

    CONSTRAINT assignment_project_fk
        FOREIGN KEY (project_id)
        REFERENCES projects(project_id)
        ON DELETE CASCADE,

    CONSTRAINT unique_employee_project
        UNIQUE (employee_id, project_id)
);


