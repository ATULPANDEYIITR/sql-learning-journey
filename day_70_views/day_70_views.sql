DO $$
DECLARE
    v_department_count INTEGER;
    v_employee_count INTEGER;
    v_project_count INTEGER;
    v_engineering_payroll NUMERIC;
BEGIN
    SELECT COUNT(*)
    INTO v_department_count
    FROM department_statistics;

    SELECT COUNT(*)
    INTO v_employee_count
    FROM employee_directory;

    SELECT COUNT(*)
    INTO v_project_count
    FROM project_workload;

    SELECT total_payroll
    INTO v_engineering_payroll
    FROM department_statistics
    WHERE department_id = 1;

    IF v_department_count <> 5 THEN
        RAISE EXCEPTION 'Department view validation failed';
    END IF;

    IF v_employee_count <> 5 THEN
        RAISE EXCEPTION 'Employee directory validation failed';
    END IF;

    IF v_project_count <> 5 THEN
        RAISE EXCEPTION 'Project view validation failed';
    END IF;

    IF v_engineering_payroll <> 207000 THEN
        RAISE EXCEPTION 'Engineering payroll validation failed';
    END IF;

    RAISE NOTICE 'All database view validations passed.';
END;
$$;


