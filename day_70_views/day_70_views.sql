-- 11. SECURITY-BARRIER VIEW
-- ============================================================================

-- A security barrier restricts certain optimizer transformations that
-- could otherwise allow user-supplied predicates to observe rows before
-- the view's security conditions have been applied.

CREATE VIEW active_employee_public
WITH (security_barrier = TRUE)
AS
SELECT
    employee_id,
    employee_name,
    department_id
FROM employees
WHERE is_active = TRUE;


