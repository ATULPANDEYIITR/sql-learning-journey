    table_name AS view_name,
    view_definition,
    is_updatable,
    is_insertable_into,
    check_option
FROM information_schema.views
WHERE table_schema = 'view_lab';


-- ============================================================================
-- 20. ELIGIBILITY EVALUATION FUNCTION
-- ============================================================================

-- Evaluates project workload against its budget and staffing conditions.

CREATE FUNCTION evaluate_project_capacity(
    p_project_id INTEGER
)
RETURNS TABLE (
    project_name VARCHAR,
    total_hours NUMERIC,
    budget NUMERIC,
    eligibility TEXT
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        p.project_name,
        COALESCE(w.total_allocated_hours, 0),
        p.budget,
        CASE
            WHEN p.project_status <> 'ACTIVE'
                THEN 'NOT_ACTIVE'
            WHEN p.budget <= 0
                THEN 'INVALID_BUDGET'
            WHEN COALESCE(w.assigned_employee_count, 0) = 0
                THEN 'NO_ASSIGNED_EMPLOYEES'
            WHEN COALESCE(w.total_allocated_hours, 0) > 500
                THEN 'CAPACITY_REVIEW_REQUIRED'
            ELSE 'ELIGIBLE'
        END
    FROM projects p
    LEFT JOIN project_workload w
        ON p.project_id = w.project_id
    WHERE p.project_id = p_project_id;
$$;


