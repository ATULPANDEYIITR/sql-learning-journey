/* ============================================================================
   8. PREDICATE PUSHDOWN AND PROJECTION
   ============================================================================ */

-- PostgreSQL can push restrictions toward base scans when semantics allow.
-- Selecting fewer columns can reduce data movement and may enable
-- index-only access when visibility-map conditions are satisfied.

EXPLAIN (ANALYZE, BUFFERS)
SELECT employee_name, salary
FROM employees
WHERE department_id = 1
  AND salary >= 90000;

-- A CTE with a single reference may be inlined by PostgreSQL.
EXPLAIN (ANALYZE, VERBOSE)
WITH engineering_employees AS (
    SELECT employee_id, employee_name, salary
    FROM employees
    WHERE department_id = 1
)
SELECT employee_name
FROM engineering_employees
WHERE salary >= 90000;

