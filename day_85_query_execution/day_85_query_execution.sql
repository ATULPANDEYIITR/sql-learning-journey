CREATE OR REPLACE FUNCTION set_execution_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.executed_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_execution_timestamp
ON query_execution_log;

CREATE TRIGGER trg_execution_timestamp
BEFORE INSERT OR UPDATE
ON query_execution_log
FOR EACH ROW
EXECUTE FUNCTION set_execution_timestamp();


/* ============================================================================
   14. QUERY PLAN SNAPSHOT FUNCTION
   ============================================================================ */

CREATE OR REPLACE FUNCTION save_plan_snapshot(
    p_query_name VARCHAR,
    p_plan JSONB,
    p_estimated_cost NUMERIC,
    p_estimated_rows BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    new_snapshot_id BIGINT;
BEGIN
    IF p_query_name IS NULL OR LENGTH(TRIM(p_query_name)) = 0 THEN
        RAISE EXCEPTION 'Query name cannot be empty.';
    END IF;

    IF p_plan IS NULL OR jsonb_typeof(p_plan) <> 'array' THEN
        RAISE EXCEPTION
            'Plan document must be a JSON array from EXPLAIN.';
    END IF;

    IF p_estimated_cost IS NOT NULL AND p_estimated_cost < 0 THEN
        RAISE EXCEPTION 'Estimated cost cannot be negative.';
    END IF;

    IF p_estimated_rows IS NOT NULL AND p_estimated_rows < 0 THEN
        RAISE EXCEPTION 'Estimated rows cannot be negative.';
    END IF;

    INSERT INTO query_plan_snapshots (
        query_name,
        plan_document,
        estimated_cost,
        estimated_rows
    )
    VALUES (
        p_query_name,
        p_plan,
        p_estimated_cost,
        p_estimated_rows
    )
    RETURNING snapshot_id INTO new_snapshot_id;

    RETURN new_snapshot_id;
END;
$$;


