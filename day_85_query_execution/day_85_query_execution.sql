/* ============================================================================
   18. EXECUTION ELIGIBILITY AND RESOURCE ESTIMATION
   ============================================================================ */

CREATE OR REPLACE FUNCTION estimate_query_eligibility(
    p_estimated_rows BIGINT,
    p_maximum_rows BIGINT,
    p_estimated_cost NUMERIC,
    p_maximum_cost NUMERIC
)
RETURNS TABLE (
    eligible BOOLEAN,
    decision_reason TEXT
)
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    IF p_estimated_rows IS NULL
       OR p_maximum_rows IS NULL
       OR p_estimated_cost IS NULL
       OR p_maximum_cost IS NULL THEN

        RETURN QUERY
        SELECT FALSE, 'Missing resource estimate'::TEXT;
        RETURN;
    END IF;

    IF p_estimated_rows < 0 OR p_maximum_rows < 0
       OR p_estimated_cost < 0 OR p_maximum_cost < 0 THEN

        RETURN QUERY
        SELECT FALSE, 'Negative resource estimate'::TEXT;
        RETURN;
    END IF;

    IF p_estimated_rows > p_maximum_rows THEN
        RETURN QUERY
        SELECT FALSE, 'Estimated row limit exceeded'::TEXT;
        RETURN;
    END IF;

    IF p_estimated_cost > p_maximum_cost THEN
        RETURN QUERY
        SELECT FALSE, 'Estimated cost limit exceeded'::TEXT;
        RETURN;
    END IF;

    RETURN QUERY
    SELECT TRUE, 'Query satisfies resource policy'::TEXT;
END;
$$;

