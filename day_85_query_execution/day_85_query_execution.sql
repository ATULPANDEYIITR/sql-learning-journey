    ON employees(employment_status);

CREATE INDEX IF NOT EXISTS idx_employees_salary
    ON employees(salary DESC);

-- Composite index supports filtering by department and status.
CREATE INDEX IF NOT EXISTS idx_employees_department_status
    ON employees(department_id, employment_status);

-- Partial index excludes inactive employees.
CREATE INDEX IF NOT EXISTS idx_active_employees_salary
    ON employees(salary DESC)
    WHERE employment_status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS idx_projects_department_status
    ON projects(department_id, project_status);

CREATE INDEX IF NOT EXISTS idx_execution_log_time
    ON query_execution_log(executed_at DESC);

CREATE INDEX IF NOT EXISTS idx_execution_log_name_time
    ON query_execution_log(query_name, executed_at DESC);

-- Covering index can support selected employee attributes.
CREATE INDEX IF NOT EXISTS idx_employee_covering
    ON employees(department_id, salary DESC)
    INCLUDE (employee_name, employment_status);


