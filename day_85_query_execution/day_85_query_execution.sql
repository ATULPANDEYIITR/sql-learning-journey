/* ============================================================================
   5. QUERY EXECUTION CONCEPTS
   ============================================================================ */

-- Parsing:
-- PostgreSQL validates SQL syntax and produces an internal parse tree.
-- Syntax errors are detected before query execution.

-- Logical analysis:
-- Names, data types, functions, operators and relations are resolved.
-- Invalid columns and incompatible expressions fail during analysis.

-- Logical planning:
-- PostgreSQL transforms the query into relational operations.
-- Predicate and projection placement can be changed when semantics permit.

-- Physical planning:
-- The optimizer chooses access methods, join algorithms, sorting methods
-- and other execution strategies.

-- Execution:
-- The executor runs the selected plan and produces rows.

-- This query may use an index or sequential scan depending on statistics.
SELECT
    employee_name,
    salary
FROM employees
WHERE department_id = 1
  AND employment_status = 'ACTIVE'
ORDER BY salary DESC
LIMIT 5;


/* ============================================================================
   6. SEQUENTIAL SCAN AND INDEX SCAN
   ============================================================================ */

-- Disable index and bitmap scans temporarily to inspect a sequential plan.
SET enable_indexscan = OFF;
SET enable_bitmapscan = OFF;

EXPLAIN
SELECT employee_name, salary
FROM employees
WHERE department_id = 1;

-- Restore normal planner behavior.
SET enable_indexscan = ON;
SET enable_bitmapscan = ON;

-- Request a plan that can use an index.
EXPLAIN
SELECT employee_id, employee_name
FROM employees
WHERE employee_id = 3;

-- EXPLAIN ANALYZE executes the statement and reports actual measurements.
EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT
    employee_name,
    salary
FROM employees
WHERE department_id = 1
  AND employment_status = 'ACTIVE'
ORDER BY salary DESC;


