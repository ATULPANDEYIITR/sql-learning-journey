CREATE TABLE IF NOT EXISTS departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(120) NOT NULL,
    department_id BIGINT NOT NULL
        REFERENCES departments(department_id),
    salary NUMERIC(12, 2) NOT NULL
        CHECK (salary >= 0),
    employment_status VARCHAR(20) NOT NULL
        CHECK (
            employment_status IN (
                'ACTIVE',
                'INACTIVE',
                'ON_LEAVE'
            )
        ),
    hired_at DATE NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(150) NOT NULL UNIQUE,
    department_id BIGINT NOT NULL
        REFERENCES departments(department_id),
    budget NUMERIC(14, 2) NOT NULL
        CHECK (budget >= 0),
    project_status VARCHAR(20) NOT NULL
        CHECK (
            project_status IN (
                'PLANNED',
                'ACTIVE',
                'COMPLETED',
                'CANCELLED'
            )
        )
);

CREATE TABLE IF NOT EXISTS employee_projects (
    employee_id BIGINT NOT NULL
        REFERENCES employees(employee_id),
    project_id BIGINT NOT NULL
        REFERENCES projects(project_id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    allocation_percent NUMERIC(5, 2) NOT NULL
        CHECK (
            allocation_percent > 0
            AND allocation_percent <= 100
        ),
    PRIMARY KEY (employee_id, project_id)
);


/* ============================================================================
   2. QUERY EXECUTION MONITORING
   ============================================================================ */

CREATE TABLE IF NOT EXISTS query_execution_log (
    execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_name VARCHAR(150) NOT NULL,
    query_category VARCHAR(40) NOT NULL
        CHECK (
            query_category IN (
                'SELECT',
                'INSERT',
                'UPDATE',
                'DELETE',
                'REPORT'
            )
        ),
    execution_status VARCHAR(20) NOT NULL
        CHECK (
            execution_status IN (
                'SUCCESS',
                'FAILED',
                'CANCELLED'
            )
        ),
    rows_processed BIGINT NOT NULL DEFAULT 0
        CHECK (rows_processed >= 0),
    execution_duration_ms NUMERIC(14, 3) NOT NULL
        CHECK (execution_duration_ms >= 0),
    access_path VARCHAR(50),
    executed_by TEXT NOT NULL DEFAULT CURRENT_USER,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS query_plan_snapshots (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_name VARCHAR(150) NOT NULL,
    plan_document JSONB NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estimated_cost NUMERIC(18, 4),
    estimated_rows BIGINT
);


