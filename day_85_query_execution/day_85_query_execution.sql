/* ============================================================================
   10. EXECUTION REPORTING VIEW
   ============================================================================ */

CREATE OR REPLACE VIEW department_execution_report AS
SELECT
    d.department_id,
    d.department_name,
    COUNT(e.employee_id) AS total_employees,
    COUNT(e.employee_id) FILTER (
        WHERE e.employment_status = 'ACTIVE'
    ) AS active_employees,
    ROUND(AVG(e.salary), 2) AS average_salary,
    MAX(e.salary) AS maximum_salary,
    MIN(e.salary) AS minimum_salary
FROM departments d
LEFT JOIN employees e
    ON e.department_id = d.department_id
GROUP BY
    d.department_id,
    d.department_name;

SELECT *
FROM department_execution_report
ORDER BY average_salary DESC NULLS LAST;


/* ============================================================================
   11. QUERY VALIDATION FUNCTION
   ============================================================================ */

CREATE OR REPLACE FUNCTION validate_employee_query(
    p_department_id BIGINT,
    p_minimum_salary NUMERIC
)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_department_id IS NULL THEN
        RETURN FALSE;
    END IF;

    IF p_minimum_salary IS NULL OR p_minimum_salary < 0 THEN
        RETURN FALSE;
    END IF;

    RETURN EXISTS (
        SELECT 1
        FROM departments
        WHERE department_id = p_department_id
    );
END;
$$;

SELECT validate_employee_query(1, 90000) AS valid_query;
SELECT validate_employee_query(9999, 90000) AS invalid_department;
SELECT validate_employee_query(1, -100) AS invalid_salary;


/* ============================================================================
   12. CONTROLLED QUERY EXECUTION PROCEDURE
   ============================================================================ */

CREATE OR REPLACE PROCEDURE execute_employee_report(
    p_department_id BIGINT,
    p_minimum_salary NUMERIC
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT validate_employee_query(
        p_department_id,
        p_minimum_salary
    ) THEN
        RAISE EXCEPTION
            'Invalid report parameters: department %, salary %',
            p_department_id,
            p_minimum_salary;
    END IF;

    -- This procedure demonstrates parameter validation.
    -- The actual result is retrieved through the reporting query.
    INSERT INTO query_execution_log (
        query_name,
        query_category,
        execution_status,
        rows_processed,
        execution_duration_ms,
        access_path
    )
    VALUES (
        'department_employee_report',
        'REPORT',
        'SUCCESS',
        (
            SELECT COUNT(*)
            FROM employees
            WHERE department_id = p_department_id
              AND salary >= p_minimum_salary
        ),
        0,
        'PLANNER_SELECTED'
    );
END;
$$;

CALL execute_employee_report(1, 90000);

SELECT
    employee_name,
    salary
FROM employees
WHERE department_id = 1
  AND salary >= 90000
ORDER BY salary DESC;


