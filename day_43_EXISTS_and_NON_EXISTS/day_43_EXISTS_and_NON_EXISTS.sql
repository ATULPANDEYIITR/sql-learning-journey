/*
 * EXISTS, NOT EXISTS, semi-joins, anti-joins, and existence checks.
 *
 * PostgreSQL-compatible script.
 *
 * Run using psql:
 *     psql -v ON_ERROR_STOP=1 -f existence_queries.sql
 *
 * The script creates an isolated schema, loads a realistic repository
 * governance dataset, executes existence queries, demonstrates integrity
 * constraints, and evaluates merge eligibility.
 */

BEGIN;

DROP SCHEMA IF EXISTS existence_lab CASCADE;
CREATE SCHEMA existence_lab;
SET search_path TO existence_lab, public;

CREATE TABLE developers (
    developer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    team_name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE repositories (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_name TEXT NOT NULL UNIQUE,
    owner_team TEXT NOT NULL,
    protected_branch BOOLEAN NOT NULL DEFAULT TRUE,
    required_approvals INTEGER NOT NULL DEFAULT 1
        CHECK (required_approvals >= 0),
    require_linear_history BOOLEAN NOT NULL DEFAULT FALSE,
    restrict_direct_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    restrict_force_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    restrict_deletion BOOLEAN NOT NULL DEFAULT TRUE,
    dismiss_stale_approvals BOOLEAN NOT NULL DEFAULT TRUE,
    require_resolved_conversations BOOLEAN NOT NULL DEFAULT TRUE,
    allow_admin_bypass BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE repository_permissions (
    repository_id BIGINT NOT NULL
        REFERENCES repositories(repository_id) ON DELETE CASCADE,
    developer_id BIGINT NOT NULL
        REFERENCES developers(developer_id) ON DELETE CASCADE,
    permission TEXT NOT NULL
        CHECK (permission IN ('read', 'write', 'maintain', 'admin')),
    PRIMARY KEY (repository_id, developer_id)
);

CREATE TABLE pull_requests (
    pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL
        REFERENCES repositories(repository_id),
    author_id BIGINT NOT NULL
        REFERENCES developers(developer_id),
    title TEXT NOT NULL,
    source_branch TEXT NOT NULL,
    target_branch TEXT NOT NULL,
    state TEXT NOT NULL
        CHECK (state IN ('open', 'draft', 'merged', 'closed')),
    base_version INTEGER NOT NULL DEFAULT 1 CHECK (base_version >= 0),
    linear_history BOOLEAN NOT NULL DEFAULT TRUE,
    conversations_resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (source_branch <> target_branch)
);

CREATE TABLE commits (
    commit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL
        REFERENCES pull_requests(pull_request_id) ON DELETE CASCADE,
    commit_hash CHAR(40) NOT NULL UNIQUE,
    parent_hash CHAR(40),
    message TEXT NOT NULL,
    committed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL
        REFERENCES pull_requests(pull_request_id) ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL
        REFERENCES developers(developer_id),
    review_state TEXT NOT NULL
        CHECK (review_state IN ('approved', 'changes_requested', 'commented')),
    reviewed_base_version INTEGER NOT NULL CHECK (reviewed_base_version >= 0),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL
        REFERENCES reviews(review_id) ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    line_number INTEGER CHECK (line_number IS NULL OR line_number > 0),
    comment_body TEXT NOT NULL,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE status_checks (
    status_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL
        REFERENCES pull_requests(pull_request_id) ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    check_state TEXT NOT NULL
        CHECK (check_state IN ('success', 'failure', 'pending')),
    evaluated_base_version INTEGER NOT NULL CHECK (evaluated_base_version >= 0),
    completed_at TIMESTAMPTZ,
    UNIQUE (pull_request_id, check_name)
);

CREATE TABLE required_checks (
    repository_id BIGINT NOT NULL
        REFERENCES repositories(repository_id) ON DELETE CASCADE,
    check_name TEXT NOT NULL,
    PRIMARY KEY (repository_id, check_name)
);

CREATE TABLE branch_protection_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL
        REFERENCES repositories(repository_id) ON DELETE CASCADE,
    actor_id BIGINT
        REFERENCES developers(developer_id),
    event_type TEXT NOT NULL
        CHECK (event_type IN (
            'direct_push_denied',
            'force_push_denied',
            'branch_deletion_denied',
            'policy_bypass',
            'merge_allowed',
            'merge_denied'
        )),
    details TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pr_repository_state
