-- EXISTS: semi-join semantics.
-- Return each open pull request with at least one current approval.
-- Multiple approvals do not duplicate a pull-request row.

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.state = 'open'
  AND EXISTS (
      SELECT 1
      FROM reviews AS r
      JOIN developers AS d
        ON d.developer_id = r.reviewer_id
      WHERE r.pull_request_id = p.pull_request_id
        AND r.review_state = 'approved'
        AND d.active
        AND r.reviewer_id <> p.author_id
        AND r.reviewed_base_version = p.base_version
  )
ORDER BY p.pull_request_id;

-- NOT EXISTS: anti-join semantics.
-- Return open pull requests without a current eligible approval.

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.state = 'open'
  AND NOT EXISTS (
      SELECT 1
      FROM reviews AS r
      JOIN developers AS d
        ON d.developer_id = r.reviewer_id
      WHERE r.pull_request_id = p.pull_request_id
        AND r.review_state = 'approved'
        AND d.active
        AND r.reviewer_id <> p.author_id
        AND r.reviewed_base_version = p.base_version
  )
ORDER BY p.pull_request_id;

-- Find pull requests with at least one unresolved review comment.
-- EXISTS avoids multiplication from multiple comments or reviews.

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.state = 'open'
  AND EXISTS (
      SELECT 1
      FROM reviews AS r
      JOIN review_comments AS c
        ON c.review_id = r.review_id
      WHERE r.pull_request_id = p.pull_request_id
        AND c.resolved = FALSE
  )
ORDER BY p.pull_request_id;

-- Find pull requests without unresolved review comments.
-- The absence of unresolved comments does not mean the review is approved.

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.state = 'open'
  AND NOT EXISTS (
      SELECT 1
      FROM reviews AS r
      JOIN review_comments AS c
        ON c.review_id = r.review_id
      WHERE r.pull_request_id = p.pull_request_id
        AND c.resolved = FALSE
  )
ORDER BY p.pull_request_id;

-- Nested anti-join: no required check may be missing or unsuccessful.
-- The inner NOT EXISTS looks for a successful result for one requirement.
-- The outer NOT EXISTS rejects a PR if any requirement lacks such a result.

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.state = 'open'
  AND p.target_branch = 'main'
  AND NOT EXISTS (
      SELECT 1
      FROM required_checks AS required
      WHERE required.repository_id = p.repository_id
        AND NOT EXISTS (
            SELECT 1
            FROM status_checks AS actual
            WHERE actual.pull_request_id = p.pull_request_id
              AND actual.check_name = required.check_name
              AND actual.check_state = 'success'
              AND actual.evaluated_base_version = p.base_version
        )
  )
ORDER BY p.pull_request_id;

-- Full merge-eligibility report.
-- Each rule is evaluated independently so failures remain explainable.
-- This is a read-only decision query; an actual merge must repeat the
-- evaluation inside an appropriate transaction with concurrency controls.

WITH approval_counts AS (
    SELECT
        p.pull_request_id,
        COUNT(DISTINCT r.reviewer_id) FILTER (
            WHERE r.review_state = 'approved'
              AND d.active
              AND r.reviewer_id <> p.author_id
              AND (
                  NOT repo.dismiss_stale_approvals
                  OR r.reviewed_base_version = p.base_version
              )
        ) AS eligible_approvals,
        EXISTS (
            SELECT 1
            FROM reviews AS change_review
            JOIN developers AS change_authority
              ON change_authority.developer_id = change_review.reviewer_id
            WHERE change_review.pull_request_id = p.pull_request_id
              AND change_review.review_state = 'changes_requested'
              AND change_authority.active
              AND change_review.reviewer_id <> p.author_id
              AND change_review.reviewed_base_version = p.base_version
        ) AS has_active_change_request
    FROM pull_requests AS p
    JOIN repositories AS repo
      ON repo.repository_id = p.repository_id
    LEFT JOIN reviews AS r
      ON r.pull_request_id = p.pull_request_id
    LEFT JOIN developers AS d
      ON d.developer_id = r.reviewer_id
    GROUP BY
        p.pull_request_id,
        p.author_id,
        p.base_version,
        repo.dismiss_stale_approvals
),
check_compliance AS (
    SELECT
        p.pull_request_id,
        NOT EXISTS (
            SELECT 1
            FROM required_checks AS required
            WHERE required.repository_id = p.repository_id
              AND NOT EXISTS (
                  SELECT 1
                  FROM status_checks AS actual
                  WHERE actual.pull_request_id = p.pull_request_id
                    AND actual.check_name = required.check_name
                    AND actual.check_state = 'success'
                    AND actual.evaluated_base_version = p.base_version
              )
        ) AS checks_pass
    FROM pull_requests AS p
),
comment_compliance AS (
    SELECT
        p.pull_request_id,
        NOT EXISTS (
            SELECT 1
            FROM reviews AS r
            JOIN review_comments AS c
              ON c.review_id = r.review_id
            WHERE r.pull_request_id = p.pull_request_id
              AND c.resolved = FALSE
        ) AS conversations_resolved
    FROM pull_requests AS p
)
SELECT
    p.pull_request_id,
    repo.repository_name,
    p.title,
    p.state,
    ac.eligible_approvals,
    repo.required_approvals,
    cc.checks_pass,
    cm.conversations_resolved,
    (
        p.state = 'open'
        AND repo.protected_branch
        AND ac.eligible_approvals >= repo.required_approvals
        AND NOT ac.has_active_change_request
        AND cc.checks_pass
        AND (
            NOT repo.require_linear_history
            OR p.linear_history
        )
        AND (
            NOT repo.require_resolved_conversations
            OR (
                p.conversations_resolved
                AND cm.conversations_resolved
            )
        )
        AND (
            NOT repo.restrict_direct_pushes
            OR EXISTS (
                SELECT 1
                FROM repository_permissions AS permission
                WHERE permission.repository_id = p.repository_id
                  AND permission.developer_id = p.author_id
                  AND permission.permission IN (
                      'write', 'maintain', 'admin'
                  )
            )
        )
    ) AS merge_eligible
FROM pull_requests AS p
JOIN repositories AS repo
  ON repo.repository_id = p.repository_id
JOIN approval_counts AS ac
  ON ac.pull_request_id = p.pull_request_id
JOIN check_compliance AS cc
  ON cc.pull_request_id = p.pull_request_id
JOIN comment_compliance AS cm
  ON cm.pull_request_id = p.pull_request_id
ORDER BY p.pull_request_id;

-- Relational division:
-- Find repositories where every required check has at least one successful
-- result on an open pull request. The outer EXISTS excludes repositories
-- with no requirements, avoiding vacuous truth for this business question.

SELECT repo.repository_id, repo.repository_name
FROM repositories AS repo
WHERE EXISTS (
    SELECT 1
    FROM required_checks AS requirement
    WHERE requirement.repository_id = repo.repository_id
)
AND NOT EXISTS (
    SELECT 1
    FROM required_checks AS requirement
    WHERE requirement.repository_id = repo.repository_id
      AND NOT EXISTS (
          SELECT 1
          FROM pull_requests AS p
          JOIN status_checks AS actual
            ON actual.pull_request_id = p.pull_request_id
          WHERE p.repository_id = repo.repository_id
            AND p.state = 'open'
            AND actual.check_name = requirement.check_name
            AND actual.check_state = 'success'
            AND actual.evaluated_base_version = p.base_version
      )
)
ORDER BY repo.repository_id;

-- Compare ordinary JOIN and EXISTS.
-- The join can return multiple rows for a pull request with multiple reviews.
-- EXISTS preserves the outer relation's cardinality.

SELECT p.pull_request_id, r.reviewer_id
FROM pull_requests AS p
JOIN reviews AS r
  ON r.pull_request_id = p.pull_request_id
WHERE p.pull_request_id = 101
  AND r.review_state = 'approved'
ORDER BY r.reviewer_id;

SELECT p.pull_request_id, p.title
FROM pull_requests AS p
WHERE p.pull_request_id = 101
  AND EXISTS (
      SELECT 1
      FROM reviews AS r
      WHERE r.pull_request_id = p.pull_request_id
        AND r.review_state = 'approved'
  );

-- NULL semantics:
-- NOT IN can produce UNKNOWN when its subquery includes NULL.
-- NOT EXISTS is generally safer for anti-join logic involving nullable data.

WITH reviewer_candidates(developer_id) AS (
    VALUES (2::BIGINT), (NULL::BIGINT)
)
SELECT d.developer_id, d.username
FROM developers AS d
WHERE d.developer_id <> 1
  AND NOT EXISTS (
      SELECT 1
      FROM reviewer_candidates AS candidate
      WHERE candidate.developer_id = d.developer_id
  )
ORDER BY d.developer_id;

WITH reviewer_candidates(developer_id) AS (
    VALUES (2::BIGINT), (NULL::BIGINT)
)
SELECT d.developer_id, d.username
FROM developers AS d
WHERE d.developer_id <> 1
  AND d.developer_id NOT IN (
      SELECT candidate.developer_id
      FROM reviewer_candidates AS candidate
  )
ORDER BY d.developer_id;

-- Verify database-level integrity by attempting an invalid insert inside
-- a savepoint. The failed operation is rolled back without aborting the
-- remainder of the demonstration.

SAVEPOINT invalid_reference_test;

DO $$
BEGIN
    BEGIN
        INSERT INTO pull_requests (
            repository_id,
            author_id,
            title,
            source_branch,
            target_branch,
            state
        )
        VALUES (
            99999,
            1,
            'Invalid repository reference',
            'feature/invalid',
            'main',
            'open'
        );

        RAISE EXCEPTION 'Expected foreign-key violation did not occur';
    EXCEPTION
        WHEN foreign_key_violation THEN
            RAISE NOTICE 'Foreign-key constraint correctly rejected invalid repository';
    END;
END;
$$;

ROLLBACK TO SAVEPOINT invalid_reference_test;
RELEASE SAVEPOINT invalid_reference_test;

-- A policy decision is not a concurrency-safe merge by itself.
-- In production, lock the relevant pull request and policy records, verify
-- current review/check versions, then update state in one transaction.
-- The following transaction demonstrates the state transition only for a
-- request that satisfies the current read-only eligibility conditions.

BEGIN;

SELECT p.pull_request_id
FROM pull_requests AS p
JOIN repositories AS repo
  ON repo.repository_id = p.repository_id
WHERE p.pull_request_id = 101
  AND p.state = 'open'
  AND repo.protected_branch
  AND NOT EXISTS (
      SELECT 1
      FROM required_checks AS requirement
      WHERE requirement.repository_id = p.repository_id
        AND NOT EXISTS (
            SELECT 1
            FROM status_checks AS actual
            WHERE actual.pull_request_id = p.pull_request_id
              AND actual.check_name = requirement.check_name
              AND actual.check_state = 'success'
              AND actual.evaluated_base_version = p.base_version
        )
  )
  AND (
      SELECT COUNT(DISTINCT r.reviewer_id)
      FROM reviews AS r
      JOIN developers AS d
        ON d.developer_id = r.reviewer_id
      WHERE r.pull_request_id = p.pull_request_id
        AND r.review_state = 'approved'
        AND d.active
        AND r.reviewer_id <> p.author_id
        AND r.reviewed_base_version = p.base_version
  ) >= repo.required_approvals
FOR UPDATE OF p;

-- This guarded update is illustrative. It independently verifies core
-- conditions so a non-eligible request cannot be updated merely because
-- a previous SELECT returned a row.
UPDATE pull_requests AS p
SET state = 'merged'
WHERE p.pull_request_id = 101
  AND p.state = 'open'
  AND EXISTS (
      SELECT 1
      FROM repositories AS repo
      WHERE repo.repository_id = p.repository_id
        AND repo.protected_branch
        AND (
            NOT repo.require_linear_history
            OR p.linear_history
        )
        AND (
            NOT repo.require_resolved_conversations
            OR p.conversations_resolved
        )
        AND (
            NOT repo.restrict_direct_pushes
            OR EXISTS (
                SELECT 1
                FROM repository_permissions AS permission
                WHERE permission.repository_id = p.repository_id
                  AND permission.developer_id = p.author_id
                  AND permission.permission IN ('write', 'maintain', 'admin')
            )
        )
        AND (
            SELECT COUNT(DISTINCT r.reviewer_id)
            FROM reviews AS r
            JOIN developers AS d
              ON d.developer_id = r.reviewer_id
            WHERE r.pull_request_id = p.pull_request_id
              AND r.review_state = 'approved'
              AND d.active
              AND r.reviewer_id <> p.author_id
              AND r.reviewed_base_version = p.base_version
        ) >= repo.required_approvals
        AND NOT EXISTS (
            SELECT 1
            FROM reviews AS r
            JOIN developers AS d
              ON d.developer_id = r.reviewer_id
            WHERE r.pull_request_id = p.pull_request_id
              AND r.review_state = 'changes_requested'
              AND d.active
              AND r.reviewer_id <> p.author_id
              AND r.reviewed_base_version = p.base_version
        )
        AND NOT EXISTS (
            SELECT 1
            FROM required_checks AS requirement
            WHERE requirement.repository_id = p.repository_id
              AND NOT EXISTS (
                  SELECT 1
                  FROM status_checks AS actual
                  WHERE actual.pull_request_id = p.pull_request_id
                    AND actual.check_name = requirement.check_name
                    AND actual.check_state = 'success'
                    AND actual.evaluated_base_version = p.base_version
              )
        )
        AND (
            NOT repo.require_resolved_conversations
            OR NOT EXISTS (
                SELECT 1
                FROM reviews AS r
                JOIN review_comments AS c
                  ON c.review_id = r.review_id
                WHERE r.pull_request_id = p.pull_request_id
                  AND c.resolved = FALSE
            )
        )
  );

COMMIT;

