-- Customers represent the buyer side of the sales model.
CREATE TABLE customers (
    customer_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name    TEXT NOT NULL,
    email            TEXT NOT NULL UNIQUE,
    city             TEXT NOT NULL,
    credit_limit     NUMERIC(14,2) NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT customers_name_ck CHECK (btrim(customer_name) <> ''),
    CONSTRAINT customers_email_ck CHECK (position('@' IN email) > 1),
    CONSTRAINT customers_credit_ck CHECK (credit_limit >= 0)
);

CREATE TABLE products (
    product_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name     TEXT NOT NULL,
    category         TEXT NOT NULL,
    unit_price       NUMERIC(14,2) NOT NULL,
    stock_quantity   INTEGER NOT NULL DEFAULT 0,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT products_name_ck CHECK (btrim(product_name) <> ''),
    CONSTRAINT products_category_ck CHECK (btrim(category) <> ''),
    CONSTRAINT products_price_ck CHECK (unit_price > 0),
    CONSTRAINT products_stock_ck CHECK (stock_quantity >= 0),
    CONSTRAINT products_name_category_uq UNIQUE (product_name, category)
);

CREATE TABLE orders (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT NOT NULL REFERENCES customers(customer_id),
    order_date       DATE NOT NULL,
    status           TEXT NOT NULL DEFAULT 'PENDING',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT orders_status_ck
        CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'CANCELLED'))
);

CREATE TABLE order_items (
    order_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id       BIGINT NOT NULL REFERENCES products(product_id),
    quantity         INTEGER NOT NULL,
    unit_price       NUMERIC(14,2) NOT NULL,
    CONSTRAINT order_items_quantity_ck CHECK (quantity > 0),
    CONSTRAINT order_items_price_ck CHECK (unit_price > 0),
    CONSTRAINT order_items_order_product_uq UNIQUE (order_id, product_id)
);

-- Status checks are automated validations associated with an order.
CREATE TABLE status_checks (
    status_check_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    check_name       TEXT NOT NULL,
    status           TEXT NOT NULL,
    checked_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT status_checks_status_ck
        CHECK (status IN ('PENDING', 'PASSED', 'FAILED')),
    CONSTRAINT status_checks_name_uq UNIQUE (order_id, check_name)
);

CREATE TABLE sales_audit (
    audit_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT REFERENCES orders(order_id) ON DELETE SET NULL,
    old_status       TEXT,
    new_status       TEXT NOT NULL,
    changed_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes support the common reporting paths rather than every column.
CREATE INDEX orders_customer_date_idx
    ON orders (customer_id, order_date);

CREATE INDEX orders_status_date_idx
    ON orders (status, order_date);

CREATE INDEX order_items_product_idx
    ON order_items (product_id);

CREATE INDEX products_category_idx
    ON products (category);

CREATE INDEX status_checks_order_status_idx
    ON status_checks (order_id, status);

CREATE OR REPLACE FUNCTION validate_order_item_price()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_price NUMERIC(14,2);
BEGIN
    SELECT unit_price
    INTO current_price
    FROM products
    WHERE product_id = NEW.product_id;

    IF current_price IS NULL THEN
        RAISE EXCEPTION 'Product % does not exist', NEW.product_id;
    END IF;

    IF NEW.unit_price <= 0 THEN
        RAISE EXCEPTION 'Order item price must be positive';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER order_item_price_validation
BEFORE INSERT OR UPDATE ON order_items
FOR EACH ROW
EXECUTE FUNCTION validate_order_item_price();

CREATE OR REPLACE FUNCTION audit_order_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO sales_audit(order_id, old_status, new_status)
        VALUES (NEW.order_id, OLD.status, NEW.status);
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER orders_status_audit
AFTER UPDATE OF status ON orders
FOR EACH ROW
EXECUTE FUNCTION audit_order_status();

CREATE OR REPLACE FUNCTION enforce_order_status_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'PENDING'
       AND NEW.status NOT IN ('PENDING', 'PAID', 'CANCELLED') THEN
        RAISE EXCEPTION 'Invalid PENDING transition to %', NEW.status;
    END IF;

    IF OLD.status = 'PAID'
       AND NEW.status NOT IN ('PAID', 'SHIPPED', 'CANCELLED') THEN
        RAISE EXCEPTION 'Invalid PAID transition to %', NEW.status;
    END IF;

    IF OLD.status IN ('SHIPPED', 'CANCELLED')
       AND NEW.status <> OLD.status THEN
        RAISE EXCEPTION 'Terminal order status % cannot be changed', OLD.status;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER orders_status_transition
BEFORE UPDATE OF status ON orders
FOR EACH ROW
EXECUTE FUNCTION enforce_order_status_transition();

CREATE OR REPLACE FUNCTION create_sales_order(
    p_customer_id BIGINT,
    p_order_date DATE,
    p_product_id BIGINT,
    p_quantity INTEGER
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_order_id BIGINT;
    v_price NUMERIC(14,2);
    v_stock INTEGER;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be positive';
    END IF;

    SELECT unit_price, stock_quantity
    INTO v_price, v_stock
    FROM products
    WHERE product_id = p_product_id
      AND active = TRUE
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Active product % does not exist', p_product_id;
    END IF;

    IF v_stock < p_quantity THEN
        RAISE EXCEPTION
            'Insufficient stock: requested %, available %',
            p_quantity, v_stock;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM customers
        WHERE customer_id = p_customer_id
    ) THEN
        RAISE EXCEPTION 'Customer % does not exist', p_customer_id;
    END IF;

    INSERT INTO orders(customer_id, order_date, status)
    VALUES (p_customer_id, p_order_date, 'PENDING')
    RETURNING order_id INTO v_order_id;

    INSERT INTO order_items(order_id, product_id, quantity, unit_price)
    VALUES (v_order_id, p_product_id, p_quantity, v_price);

    UPDATE products
    SET stock_quantity = stock_quantity - p_quantity
    WHERE product_id = p_product_id;

    RETURN v_order_id;
END;
$$;

