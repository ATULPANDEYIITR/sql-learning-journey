CREATE OR REPLACE VIEW completed_order_revenue AS
SELECT
    o.order_id,
    o.order_date,
    o.customer_id,
    c.customer_name,
    SUM(oi.quantity * oi.unit_price)::NUMERIC(14,2) AS order_revenue
FROM orders o
JOIN customers c
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON oi.order_id = o.order_id
WHERE o.status IN ('PAID', 'SHIPPED')
GROUP BY
    o.order_id,
    o.order_date,
    o.customer_id,
    c.customer_name;

CREATE OR REPLACE VIEW customer_revenue AS
SELECT
    c.customer_id,
    c.customer_name,
    c.city,
    COUNT(DISTINCT r.order_id) AS completed_orders,
    COALESCE(SUM(r.order_revenue), 0)::NUMERIC(14,2) AS revenue
FROM customers c
LEFT JOIN completed_order_revenue r
    ON r.customer_id = c.customer_id
GROUP BY c.customer_id, c.customer_name, c.city;

-- Retrieval: detailed completed orders.
SELECT *
FROM completed_order_revenue
ORDER BY order_date, order_id;

-- Aggregation: customer revenue ranking.
SELECT
    customer_name,
    completed_orders,
    revenue,
    RANK() OVER (ORDER BY revenue DESC) AS revenue_rank
FROM customer_revenue
ORDER BY revenue DESC;

-- Product analysis: units sold and generated revenue.
SELECT
    p.product_id,
    p.product_name,
    p.category,
    COALESCE(SUM(
        CASE
            WHEN o.status IN ('PAID', 'SHIPPED') THEN oi.quantity
            ELSE 0
        END
    ), 0) AS units_sold,
    COALESCE(SUM(
        CASE
            WHEN o.status IN ('PAID', 'SHIPPED')
            THEN oi.quantity * oi.unit_price
            ELSE 0
        END
    ), 0)::NUMERIC(14,2) AS revenue
FROM products p
LEFT JOIN order_items oi
    ON oi.product_id = p.product_id
LEFT JOIN orders o
    ON o.order_id = oi.order_id
GROUP BY p.product_id, p.product_name, p.category
ORDER BY revenue DESC;

-- Monthly revenue trend.
SELECT
    date_trunc('month', order_date)::DATE AS month,
    SUM(order_revenue)::NUMERIC(14,2) AS revenue
FROM completed_order_revenue
GROUP BY date_trunc('month', order_date)
ORDER BY month;

-- Category performance using a CTE.
WITH category_sales AS (
    SELECT
        p.category,
        SUM(oi.quantity * oi.unit_price)::NUMERIC(14,2) AS revenue
    FROM order_items oi
    JOIN orders o ON o.order_id = oi.order_id
    JOIN products p ON p.product_id = oi.product_id
    WHERE o.status IN ('PAID', 'SHIPPED')
    GROUP BY p.category
)
SELECT
    category,
    revenue,
    ROUND(
        100.0 * revenue / NULLIF(SUM(revenue) OVER (), 0),
        2
    ) AS revenue_share_percent
FROM category_sales
ORDER BY revenue DESC;

-- Workflow validation: identify orders whose required checks are incomplete.
SELECT
    o.order_id,
    o.status,
    COUNT(*) FILTER (WHERE sc.status = 'PASSED') AS passed_checks,
    COUNT(*) FILTER (WHERE sc.status = 'FAILED') AS failed_checks,
    COUNT(*) FILTER (WHERE sc.status = 'PENDING') AS pending_checks
FROM orders o
LEFT JOIN status_checks sc
    ON sc.order_id = o.order_id
GROUP BY o.order_id, o.status
HAVING COUNT(*) FILTER (WHERE sc.status IN ('FAILED', 'PENDING')) > 0
ORDER BY o.order_id;

-- Eligibility example: a customer can be considered a high-value account
-- when completed revenue exceeds its configured credit limit.
SELECT
    customer_id,
    customer_name,
    credit_limit,
    revenue,
    CASE
        WHEN revenue > credit_limit THEN 'ABOVE_CREDIT_LIMIT'
        WHEN revenue > 0 THEN 'WITHIN_CREDIT_LIMIT'
        ELSE 'NO_COMPLETED_SALES'
    END AS revenue_classification
FROM customer_revenue
JOIN customers USING (customer_id)
ORDER BY revenue DESC;

