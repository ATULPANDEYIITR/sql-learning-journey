-- 11. CYCLE SEQUENCE
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS temporary_code_seq
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 3
    CYCLE;

SELECT nextval('temporary_code_seq');
SELECT nextval('temporary_code_seq');
SELECT nextval('temporary_code_seq');
SELECT nextval('temporary_code_seq');
SELECT nextval('temporary_code_seq');

-- CYCLE permits value reuse.
-- Therefore, a cycling sequence must not be assumed to provide
-- permanently unique primary keys.

-- ============================================================================
-- 12. CACHE CONFIGURATION
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS cached_order_seq
    START WITH 1
    INCREMENT BY 1
    CACHE 20
    NO CYCLE;

ALTER SEQUENCE cached_order_seq
    CACHE 50;

SELECT nextval('cached_order_seq');

-- Cache improves allocation performance by reserving multiple values.
-- Different database sessions can reserve separate ranges.
-- Unused cached values can be lost after disconnection or failure.
-- Observed values need not form a gap-free series.

-- ============================================================================
-- 13. TRANSACTION ROLLBACK AND SEQUENCE GAPS
-- ============================================================================

CREATE TABLE IF NOT EXISTS rollback_demo (
    id BIGINT PRIMARY KEY DEFAULT nextval(
        'sequence_lab.rollback_demo_seq'::regclass
    ),

    description TEXT NOT NULL
);

CREATE SEQUENCE IF NOT EXISTS rollback_demo_seq
    START WITH 1
    INCREMENT BY 1
    CACHE 1;

ALTER SEQUENCE rollback_demo_seq
    OWNED BY rollback_demo.id;

-- The table references the sequence.
-- The sequence must exist before the table default is used.
-- Both objects have now been created in dependency-safe order.

BEGIN;

INSERT INTO rollback_demo(description)
VALUES ('This record will be rolled back');

SELECT currval('rollback_demo_seq');

ROLLBACK;

-- The inserted row is absent, but the allocated sequence value
-- remains consumed.

SELECT *
FROM rollback_demo;

SELECT nextval('rollback_demo_seq') AS value_after_rollback;

-- Sequence operations are not transactional in the same way as
-- ordinary table modifications.

-- ============================================================================
-- 14. SEQUENCE SYNCHRONIZATION AFTER DATA IMPORT
-- ============================================================================

-- Explicitly inserted IDs do not automatically advance an associated
-- sequence.

INSERT INTO imported_customers (
    customer_id,
    customer_name,
    external_reference
)
OVERRIDING SYSTEM VALUE
VALUES (
    9000,
    'Bulk Imported Customer',
    'BULK-9000'
);

-- Synchronize the sequence to the current maximum ID.
-- This must be performed with appropriate coordination to prevent
-- concurrent inserts from racing with the reset.

SELECT setval(
    pg_get_serial_sequence(
        'sequence_lab.imported_customers',
        'customer_id'
    ),
    COALESCE(
        (SELECT MAX(customer_id) FROM imported_customers),
        1
    ),
    EXISTS (
        SELECT 1
        FROM imported_customers
    )
);

INSERT INTO imported_customers (
    customer_name,
    external_reference
)
VALUES (
    'Post Import Customer',
    'POST-IMPORT-9001'
);

-- ============================================================================
-- 15. SAFE SEQUENCE SYNCHRONIZATION FUNCTION
-- ============================================================================

CREATE OR REPLACE FUNCTION synchronize_customer_sequence()
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    maximum_id BIGINT;
    sequence_name REGCLASS;
BEGIN
    LOCK TABLE imported_customers IN SHARE ROW EXCLUSIVE MODE;

    SELECT COALESCE(MAX(customer_id), 1)
    INTO maximum_id
    FROM imported_customers;

    sequence_name := pg_get_serial_sequence(
        'sequence_lab.imported_customers',
        'customer_id'
    )::REGCLASS;

    IF sequence_name IS NULL THEN
        RAISE EXCEPTION
            'No associated sequence found for imported_customers.customer_id';
    END IF;

    PERFORM setval(
        sequence_name,
        maximum_id,
        EXISTS (
            SELECT 1
            FROM imported_customers
        )
    );

    RETURN maximum_id;
END;
$$;

SELECT synchronize_customer_sequence();

