-- 16. AUDIT TABLE AND SEQUENCE ALLOCATION TRIGGER
-- ============================================================================

CREATE TABLE IF NOT EXISTS sequence_allocation_audit (
    audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    sequence_name TEXT NOT NULL,

    allocated_value BIGINT NOT NULL,

    session_user_name TEXT NOT NULL DEFAULT SESSION_USER,

    allocated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION audit_order_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO sequence_allocation_audit (
        sequence_name,
        allocated_value
    )
    VALUES (
        'order_number_seq',
        NEW.order_id
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_order_insert ON orders;

CREATE TRIGGER trg_audit_order_insert
AFTER INSERT ON orders
FOR EACH ROW
EXECUTE FUNCTION audit_order_insert();

INSERT INTO orders (
    customer_name,
    order_amount
)
VALUES (
    'Audit Customer',
    12500.00
);

SELECT *
FROM sequence_allocation_audit
ORDER BY audit_id;

-- This trigger records successful row insertions, not every NEXTVAL
-- call. Values consumed by failed inserts or rolled-back transactions
-- will not necessarily appear in this audit table.

