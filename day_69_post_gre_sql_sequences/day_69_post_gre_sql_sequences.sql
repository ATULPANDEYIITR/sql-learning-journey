        RAISE EXCEPTION
            'Expected duplicate primary-key violation.';

    EXCEPTION
        WHEN unique_violation THEN
            RAISE NOTICE
                'Expected behavior: duplicate primary key rejected.';
    END;
END;
$$;

-- ============================================================================
-- 21. REPORTING AND AGGREGATION
-- ============================================================================

SELECT
    order_status,
    COUNT(*) AS total_orders,
    SUM(order_amount) AS total_amount,
    AVG(order_amount) AS average_amount,
    MIN(order_id) AS first_order_id,
    MAX(order_id) AS latest_order_id
FROM orders
GROUP BY order_status
ORDER BY order_status;

-- ============================================================================
-- 22. CTE-BASED IDENTIFIER ANALYSIS
-- ============================================================================

WITH order_statistics AS (
    SELECT
        COUNT(*) AS total_orders,
        MIN(order_id) AS minimum_id,
        MAX(order_id) AS maximum_id
    FROM orders
),
sequence_configuration AS (
    SELECT
        sequencename,
        last_value,
        increment_by,
        cache_size
    FROM pg_sequences
    WHERE schemaname = 'sequence_lab'
      AND sequencename = 'order_number_seq'
)
SELECT
    order_statistics.total_orders,
    order_statistics.minimum_id,
    order_statistics.maximum_id,
    sequence_configuration.last_value,
    sequence_configuration.increment_by,
    sequence_configuration.cache_size,
    CASE
        WHEN order_statistics.maximum_id IS NULL
            THEN 'NO RECORDS'
        WHEN sequence_configuration.last_value IS NULL
            THEN 'SEQUENCE STATE NOT VISIBLE'
        WHEN sequence_configuration.last_value
             < order_statistics.maximum_id
            THEN 'POTENTIAL SYNCHRONIZATION REQUIRED'
        ELSE 'SEQUENCE AT OR BEYOND TABLE MAXIMUM'
    END AS synchronization_status
FROM order_statistics
CROSS JOIN sequence_configuration;

-- This report is an operational indicator, not a concurrency-safe
-- proof that a sequence is ready for resetting.

