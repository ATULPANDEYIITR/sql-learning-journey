-- ============================================================================
-- 2. EXPLICIT SEQUENCE
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS order_number_seq
    AS BIGINT
    START WITH 1000
    INCREMENT BY 1
    MINVALUE 1000
    MAXVALUE 999999999999
    CACHE 1
    NO CYCLE;

COMMENT ON SEQUENCE order_number_seq IS
'Explicit order number sequence for order processing.';

CREATE TABLE IF NOT EXISTS orders (
    order_id BIGINT PRIMARY KEY
        DEFAULT nextval('sequence_lab.order_number_seq'::regclass),

    customer_name VARCHAR(150) NOT NULL,

    order_amount NUMERIC(14, 2) NOT NULL
        CHECK (order_amount >= 0),

    order_status VARCHAR(20) NOT NULL
        DEFAULT 'PENDING'
        CHECK (
            order_status IN (
                'PENDING',
                'PROCESSING',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Establish ownership so the sequence follows the column lifecycle.
ALTER SEQUENCE order_number_seq
    OWNED BY orders.order_id;

CREATE INDEX IF NOT EXISTS idx_orders_created_at
    ON orders(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_orders_status
    ON orders(order_status);

