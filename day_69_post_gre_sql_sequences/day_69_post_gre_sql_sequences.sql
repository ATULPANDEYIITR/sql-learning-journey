-- 23. PERFORMANCE AND ACCESS CONTROL
-- ============================================================================

-- Sequence privileges are separate from table privileges.

REVOKE ALL ON SEQUENCE order_number_seq FROM PUBLIC;

-- Example application role creation is intentionally conditional.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'sequence_app'
    ) THEN
        CREATE ROLE sequence_app NOLOGIN;
    END IF;
END;
$$;

GRANT USAGE, SELECT
ON SEQUENCE order_number_seq
TO sequence_app;

GRANT SELECT, INSERT
ON orders
TO sequence_app;

-- USAGE permits NEXTVAL and CURRVAL.
-- SELECT permits reading sequence state and CURRVAL.
-- UPDATE permits SETVAL and other sequence modifications.
-- Grant UPDATE only to trusted maintenance roles.

