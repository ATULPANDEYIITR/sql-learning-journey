-- ============================================================================
-- 8. NEXTVAL, CURRVAL AND LASTVAL
-- ============================================================================

-- NEXTVAL atomically obtains and advances a sequence value.
SELECT nextval('order_number_seq');

-- CURRVAL returns the last NEXTVAL value for this session and sequence.
-- It fails if NEXTVAL has not previously been called in this session.
SELECT currval('order_number_seq');

-- LASTVAL returns the most recent NEXTVAL obtained in this session
-- from any sequence.
SELECT lastval();

-- Inspect the sequence relation.
SELECT *
FROM order_number_seq;

-- ============================================================================
-- 9. SETVAL BEHAVIOR
-- ============================================================================

-- The next NEXTVAL advances from 5000.
SELECT setval('order_number_seq', 5000, true);

SELECT nextval('order_number_seq');

-- The next NEXTVAL returns exactly 8000.
SELECT setval('order_number_seq', 8000, false);

SELECT nextval('order_number_seq');

