-- Primary-key constraints enforce uniqueness even when identifiers
-- are manually inserted or sequence configuration is incorrect.

DO $$
BEGIN
    BEGIN
        INSERT INTO legacy_customers (
            customer_id,
            customer_name,
            email
        )
        OVERRIDING SYSTEM VALUE
        VALUES (
            1,
            'Duplicate Customer',
