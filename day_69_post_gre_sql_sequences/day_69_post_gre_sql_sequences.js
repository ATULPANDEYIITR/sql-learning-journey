'use strict';

/**
 * PostgreSQL Sequence Management
 *
 * Node.js implementation covering:
 * - Sequence configuration and validation
 * - SERIAL and IDENTITY behavior
 * - Asynchronous allocation
 * - Session-specific CURRVAL
 * - SETVAL and RESTART
 * - Sequence boundaries and cycling
 * - Cache allocation behavior
 * - Transaction rollback gaps
 * - Event-driven monitoring
 * - Concurrent allocation
 *
 * Runtime: Node.js 18+
 * Dependencies: None
 */

const fs = require('node:fs/promises');
const path = require('node:path');
const { EventEmitter } = require('node:events');

class SequenceError extends Error {}
class SequenceLimitError extends SequenceError {}
class SequenceConfigurationError extends SequenceError {}
class IdentityError extends SequenceError {}
class DuplicateKeyError extends SequenceError {}

const IdentityMode = Object.freeze({
    SERIAL: 'SERIAL',
    ALWAYS: 'GENERATED ALWAYS',
    BY_DEFAULT: 'GENERATED BY DEFAULT'
});

function validateConfig(config) {
    const {
        name,
        start = 1,
        increment = 1,
        minValue = 1,
        maxValue = 9223372036854775807n,
        cache = 1,
        cycle = false
    } = config;

    if (typeof name !== 'string' || !name.trim()) {
        throw new SequenceConfigurationError(
            'A valid sequence name is required.'
        );
    }

    const values = [start, increment, minValue, maxValue, cache];

    for (const value of values) {
        if (!Number.isSafeInteger(value)) {
            throw new SequenceConfigurationError(
                'Sequence configuration values must be safe integers.'
            );
        }
    }

    if (increment === 0) {
        throw new SequenceConfigurationError(
            'Increment cannot be zero.'
        );
    }

    if (minValue > maxValue || start < minValue || start > maxValue) {
        throw new SequenceConfigurationError(
            'Invalid sequence boundaries.'
        );
    }

    if (cache < 1) {
        throw new SequenceConfigurationError(
            'Cache must be at least one.'
        );
    }

    if (typeof cycle !== 'boolean') {
        throw new SequenceConfigurationError(
            'Cycle must be a boolean.'
        );
    }

    return {
        name,
        start,
        increment,
        minValue,
        maxValue,
        cache,
        cycle
    };
}

class SequenceManager extends EventEmitter {
    constructor(config) {
        super();

        this.config = validateConfig(config);

        this.lastValue = null;
        this.isCalled = false;
        this.allocations = 0;

        this.sessions = new Map();

        // Promise queue serializes mutations in this process.
        this.queue = Promise.resolve();
    }

    async executeExclusive(operation) {
        const result = this.queue.then(operation);

        this.queue = result.catch(() => {});

        return result;
    }

    calculateNext() {
        const config = this.config;

        if (!this.isCalled) {
            return config.start;
        }

        const candidate = this.lastValue + config.increment;

        if (
            config.increment > 0 &&
            candidate > config.maxValue
        ) {
            if (!config.cycle) {
                throw new SequenceLimitError(
                    `${config.name} reached its maximum.`
                );
            }

            return config.minValue;
        }

        if (
            config.increment < 0 &&
            candidate < config.minValue
        ) {
            if (!config.cycle) {
                throw new SequenceLimitError(
                    `${config.name} reached its minimum.`
                );
            }

            return config.maxValue;
        }

        return candidate;
    }

    async nextval(sessionId = 'default') {
        if (!sessionId || typeof sessionId !== 'string') {
            throw new TypeError('Valid session ID required.');
        }

        return this.executeExclusive(async () => {
            const value = this.calculateNext();

            this.lastValue = value;
            this.isCalled = true;
            this.allocations++;

            this.sessions.set(sessionId, value);

            this.emit('allocated', {
                sequence: this.config.name,
                sessionId,
                value,
                allocation: this.allocations
            });

            return value;
        });
    }

    currval(sessionId = 'default') {
        if (!this.sessions.has(sessionId)) {
            throw new SequenceError(
                `Session ${sessionId} has not called NEXTVAL.`
            );
        }

        return this.sessions.get(sessionId);
    }

    async setval(value, isCalled = true) {
        if (
            !Number.isSafeInteger(value) ||
            value < this.config.minValue ||
            value > this.config.maxValue
        ) {
            throw new SequenceLimitError(
                'SETVAL value is outside sequence limits.'
            );
        }

        return this.executeExclusive(async () => {
            this.lastValue = value;
            this.isCalled = isCalled;

            this.emit('reset', {
                sequence: this.config.name,
                value,
                isCalled
            });

            return value;
        });
    }

    async restart(value = this.config.start) {
        if (
            !Number.isSafeInteger(value) ||
            value < this.config.minValue ||
            value > this.config.maxValue
        ) {
            throw new SequenceLimitError(
                'Invalid restart value.'
            );
        }

        return this.executeExclusive(async () => {
            this.lastValue = value;
            this.isCalled = false;
            this.sessions.clear();

            this.emit('restarted', {
                sequence: this.config.name,
                value
            });
        });
    }

    snapshot() {
        return {
            name: this.config.name,
            lastValue: this.lastValue,
            isCalled: this.isCalled,
            allocations: this.allocations,
            cache: this.config.cache,
            cycle: this.config.cycle
        };
    }
}

class IdentityTable {
    constructor(sequence, mode = IdentityMode.ALWAYS) {
        this.sequence = sequence;
        this.mode = mode;
        this.records = new Map();
    }

    async insert(data, options = {}) {
        const {
            id = null,
            overridingSystemValue = false,
            sessionId = 'application'
        } = options;

        if (
            !data ||
            typeof data.name !== 'string' ||
            !data.name.trim()
        ) {
            throw new TypeError('Customer name is required.');
        }

        if (
            typeof data.email !== 'string' ||
            !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(data.email)
        ) {
            throw new TypeError('Valid customer email is required.');
        }

        let customerId;

        if (id !== null) {
            if (
                this.mode === IdentityMode.ALWAYS &&
                !overridingSystemValue
            ) {
                throw new IdentityError(
                    'GENERATED ALWAYS rejects explicit IDs.'
                );
            }

            customerId = id;
        } else {
            customerId = await this.sequence.nextval(sessionId);
        }

        if (!Number.isSafeInteger(customerId) || customerId <= 0) {
            throw new TypeError('Customer ID must be positive.');
        }

        if (this.records.has(customerId)) {
            throw new DuplicateKeyError(
                `Customer ${customerId} already exists.`
            );
        }

        const customer = Object.freeze({
            id: customerId,
            name: data.name.trim(),
            email: data.email.trim().toLowerCase(),
            createdAt: new Date().toISOString()
        });

        this.records.set(customerId, customer);

        return customer;
    }

    find(id) {
        return this.records.get(id) ?? null;
    }

    async synchronizeSequence() {
        const maximumId = Math.max(0, ...this.records.keys());

        const current = this.sequence.snapshot().lastValue;

        if (current === null || maximumId > current) {
            await this.sequence.setval(maximumId, true);
        }

        return maximumId;
    }
}

class TransactionSimulator {
    constructor(sequence) {
        this.sequence = sequence;
    }

    async execute(operation) {
        const allocated = [];

        try {
            const result = await operation({
                nextval: async () => {
                    const value = await this.sequence.nextval(
                        'transaction'
                    );

                    allocated.push(value);
                    return value;
                }
            });

            return {
                committed: true,
                allocated,
                result
            };
        } catch (error) {
            // Simulates rollback of application data.
            // Sequence values are not restored.
            return {
                committed: false,
                allocated,
                error: error.message
            };
        }
    }
}

async function demonstrateBasicSequence() {
    console.log('\n1. BASIC SEQUENCE');

    const sequence = new SequenceManager({
        name: 'orders_order_id_seq',
        start: 1000,
        increment: 1,
        minValue: 1000,
        maxValue: 1100
    });

    sequence.on('allocated', event => {
        console.log(
            `[EVENT] ${event.sequence}: ${event.value}`
        );
    });

    const first = await sequence.nextval('session-a');
    const second = await sequence.nextval('session-a');

    console.log('First:', first);
    console.log('Second:', second);
    console.log('CURRVAL:', sequence.currval('session-a'));

    return sequence;
}

async function demonstrateIdentity() {
    console.log('\n2. IDENTITY COLUMNS');

    const sequence = new SequenceManager({
        name: 'customer_id_seq'
    });

    const customers = new IdentityTable(
        sequence,
        IdentityMode.ALWAYS
    );

    const customer = await customers.insert({
        name: 'Aarav Sharma',
        email: 'aarav@example.com'
    });

    console.log('Generated customer:', customer);

    try {
        await customers.insert(
            {
                name: 'Manual Customer',
                email: 'manual@example.com'
            },
            { id: 500 }
        );
    } catch (error) {
        console.log('Expected restriction:', error.message);
    }

    await customers.insert(
        {
            name: 'Imported Customer',
            email: 'import@example.com'
        },
        {
            id: 500,
            overridingSystemValue: true
        }
    );

    await customers.synchronizeSequence();

    const next = await customers.insert({
        name: 'Next Customer',
        email: 'next@example.com'
    });

    console.log('Next generated ID:', next.id);
}

async function demonstrateSessionBehavior() {
    console.log('\n3. SESSION-SPECIFIC CURRVAL');

    const sequence = new SequenceManager({
        name: 'invoice_sequence'
    });

    await sequence.nextval('connection-1');

    try {
        sequence.currval('connection-2');
    } catch (error) {
        console.log('Expected error:', error.message);
    }

    await sequence.nextval('connection-2');

    console.log(
        'Connection 1:',
        sequence.currval('connection-1')
    );

    console.log(
        'Connection 2:',
        sequence.currval('connection-2')
    );
}

