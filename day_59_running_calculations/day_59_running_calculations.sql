-- Retrieve the complete running series.
SELECT
    stream_name,
    sequence_no,
    measurement_value,
    running_total,
    cumulative_average,
    running_minimum,
    running_maximum
FROM running_metrics
ORDER BY stream_name, sequence_no;

-- Evaluate the current cumulative state against policies.
SELECT *
FROM metric_stream_status
ORDER BY stream_name;

-- Aggregate reporting without materializing running values.
SELECT
    s.stream_name,
    COUNT(m.measurement_id) AS observation_count,
    COALESCE(SUM(m.measurement_value), 0) AS final_total,
    COALESCE(AVG(m.measurement_value), 0) AS final_average,
    MIN(m.measurement_value) AS final_minimum,
    MAX(m.measurement_value) AS final_maximum
FROM metric_streams s
LEFT JOIN measurements m
    ON m.stream_id = s.stream_id
GROUP BY s.stream_id, s.stream_name
ORDER BY s.stream_name;

-- Identify observations where the cumulative total first crosses 3,000.
WITH ranked AS (
    SELECT
        *,
        LAG(running_total) OVER (
            PARTITION BY stream_id
            ORDER BY sequence_no
        ) AS previous_total
    FROM running_metrics
)
SELECT
    stream_name,
    sequence_no,
    running_total
FROM ranked
WHERE running_total >= 3000
  AND COALESCE(previous_total, 0) < 3000
ORDER BY stream_name, sequence_no;

-- Cumulative contribution of each measurement to the final stream total.
WITH totals AS (
    SELECT
        stream_id,
        SUM(measurement_value) AS final_total
    FROM measurements
    GROUP BY stream_id
)
SELECT
    r.stream_name,
    r.sequence_no,
    r.measurement_value,
    r.running_total,
    CASE
        WHEN t.final_total = 0 THEN 0
        ELSE r.measurement_value / t.final_total * 100
    END AS percent_of_final_total
FROM running_metrics r
JOIN totals t
  ON t.stream_id = r.stream_id
ORDER BY r.stream_name, r.sequence_no;

-- Transactional failure example. The invalid source causes the transaction
-- to fail before an incomplete record can be committed.
BEGIN;

DO $$
DECLARE
    stream_key BIGINT;
BEGIN
    SELECT stream_id
    INTO stream_key
    FROM metric_streams
    WHERE stream_name = 'daily_sales';

    IF stream_key IS NULL THEN
        RAISE EXCEPTION 'daily_sales stream does not exist';
    END IF;
END;
$$;

-- The following statement is intentionally executed inside a savepoint so
-- the complete demonstration script can continue after the rejected input.
SAVEPOINT invalid_measurement;

DO $$
BEGIN
    PERFORM insert_measurement(
        (SELECT stream_id
         FROM metric_streams
         WHERE stream_name = 'daily_sales'),
        500.00,
        ''
    );
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'Rejected invalid measurement: %', SQLERRM;
END;
$$;

ROLLBACK TO SAVEPOINT invalid_measurement;
COMMIT;
