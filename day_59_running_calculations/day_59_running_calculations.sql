DROP SCHEMA IF EXISTS running_calculations CASCADE;
CREATE SCHEMA running_calculations;

SET search_path = running_calculations, public;

-- A measurement is immutable business input. Running metrics are derived from
-- ordered measurements rather than stored as independently mutable totals.
CREATE TABLE metric_streams (
    stream_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stream_name TEXT NOT NULL UNIQUE,
    metric_unit TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (btrim(stream_name) <> ''),
    CHECK (btrim(metric_unit) <> '')
);

CREATE TABLE measurements (
    measurement_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stream_id BIGINT NOT NULL REFERENCES metric_streams(stream_id)
        ON DELETE CASCADE,
    sequence_no BIGINT NOT NULL,
    measurement_value NUMERIC(18, 4) NOT NULL,
    measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source TEXT NOT NULL,
    UNIQUE (stream_id, sequence_no),
    UNIQUE (stream_id, source),
    CHECK (measurement_value BETWEEN -1000000000000 AND 1000000000000),
    CHECK (btrim(source) <> '')
);

CREATE INDEX idx_measurements_stream_sequence
    ON measurements (stream_id, sequence_no);

CREATE INDEX idx_measurements_stream_time
    ON measurements (stream_id, measured_at);

CREATE TABLE cumulative_policies (
    policy_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stream_id BIGINT NOT NULL REFERENCES metric_streams(stream_id)
        ON DELETE CASCADE,
    maximum_total NUMERIC(18, 4),
    minimum_average NUMERIC(18, 4),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (stream_id),
    CHECK (
        maximum_total IS NULL
        OR maximum_total >= 0
    )
);

-- Sequence numbers are generated by the database, preventing two concurrent
-- writers from assigning the same next position.
CREATE OR REPLACE FUNCTION assign_measurement_sequence()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.sequence_no IS NULL OR NEW.sequence_no <= 0 THEN
        SELECT COALESCE(MAX(sequence_no), 0) + 1
        INTO NEW.sequence_no
        FROM measurements
        WHERE stream_id = NEW.stream_id
        FOR UPDATE;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_assign_measurement_sequence
BEFORE INSERT ON measurements
FOR EACH ROW
EXECUTE FUNCTION assign_measurement_sequence();

CREATE OR REPLACE FUNCTION validate_measurement_sequence()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_sequence BIGINT;
BEGIN
    SELECT COALESCE(MAX(sequence_no), 0) + 1
    INTO expected_sequence
    FROM measurements
    WHERE stream_id = NEW.stream_id
      AND measurement_id <> NEW.measurement_id;

    IF NEW.sequence_no <> expected_sequence THEN
        RAISE EXCEPTION
            'sequence must be contiguous: expected %, received %',
            expected_sequence,
            NEW.sequence_no;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_measurement_sequence
BEFORE INSERT ON measurements
FOR EACH ROW
EXECUTE FUNCTION validate_measurement_sequence();

CREATE OR REPLACE VIEW running_metrics AS
SELECT
    m.measurement_id,
    m.stream_id,
    s.stream_name,
    m.sequence_no,
    m.measurement_value,
    m.measured_at,
    SUM(m.measurement_value) OVER (
        PARTITION BY m.stream_id
        ORDER BY m.sequence_no
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_total,
    AVG(m.measurement_value) OVER (
        PARTITION BY m.stream_id
        ORDER BY m.sequence_no
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS cumulative_average,
    MIN(m.measurement_value) OVER (
        PARTITION BY m.stream_id
        ORDER BY m.sequence_no
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_minimum,
    MAX(m.measurement_value) OVER (
        PARTITION BY m.stream_id
        ORDER BY m.sequence_no
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_maximum
FROM measurements m
JOIN metric_streams s
  ON s.stream_id = m.stream_id;

CREATE OR REPLACE VIEW metric_stream_status AS
WITH latest AS (
    SELECT DISTINCT ON (stream_id)
        stream_id,
        sequence_no,
        running_total,
        cumulative_average
    FROM running_metrics
    ORDER BY stream_id, sequence_no DESC
)
SELECT
    s.stream_id,
    s.stream_name,
    l.sequence_no AS latest_sequence,
    l.running_total,
    l.cumulative_average,
    p.maximum_total,
    p.minimum_average,
    CASE
        WHEN l.stream_id IS NULL THEN 'EMPTY'
        WHEN p.maximum_total IS NOT NULL
             AND l.running_total > p.maximum_total THEN 'TOTAL_LIMIT_EXCEEDED'
        WHEN p.minimum_average IS NOT NULL
             AND l.cumulative_average < p.minimum_average THEN 'AVERAGE_REQUIREMENT_NOT_MET'
        ELSE 'ELIGIBLE'
    END AS status
FROM metric_streams s
LEFT JOIN latest l
  ON l.stream_id = s.stream_id
LEFT JOIN cumulative_policies p
  ON p.stream_id = s.stream_id;

CREATE OR REPLACE FUNCTION insert_measurement(
    p_stream_id BIGINT,
    p_value NUMERIC,
    p_source TEXT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    new_id BIGINT;
BEGIN
    IF p_value IS NULL THEN
        RAISE EXCEPTION 'measurement value cannot be NULL';
    END IF;

    IF p_source IS NULL OR btrim(p_source) = '' THEN
        RAISE EXCEPTION 'measurement source cannot be empty';
    END IF;

    INSERT INTO measurements (
        stream_id,
        sequence_no,
        measurement_value,
        source
    )
    VALUES (
        p_stream_id,
        NULL,
        p_value,
        p_source
    )
    RETURNING measurement_id INTO new_id;

    RETURN new_id;
END;
$$;

