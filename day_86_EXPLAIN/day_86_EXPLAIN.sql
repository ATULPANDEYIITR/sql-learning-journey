/*
===============================================================================
SQL EXPLAIN: EXECUTION PLANS, COST ESTIMATES, AND SCAN TYPES
PostgreSQL practical execution-plan laboratory
===============================================================================

Demonstrates:

1. EXPLAIN and EXPLAIN ANALYZE
2. Estimated and actual execution behavior
3. Startup cost and total cost
4. Sequential scans
5. Index scans
6. Index-only scans
7. Bitmap index and bitmap heap scans
8. Nested loop, hash and merge joins
9. Sort and aggregate operations
10. Cardinality and selectivity
11. Statistics and ANALYZE
12. Shared buffers and temporary I/O
13. CTE execution plans
14. Execution-plan reporting
15. Transactions and safe query experimentation

Compatible with PostgreSQL 15+.

The script creates an isolated explain_lab schema.
*/

BEGIN;

CREATE SCHEMA IF NOT EXISTS explain_lab;

SET search_path TO explain_lab, public;

-- ============================================================================
-- 1. DOMAIN TABLES
-- ============================================================================

CREATE TABLE IF NOT EXISTS departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    annual_budget NUMERIC(14, 2) NOT NULL
        CHECK (annual_budget >= 0)
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(150) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE,
    department_id BIGINT NOT NULL
        REFERENCES departments(department_id),
    salary NUMERIC(12, 2) NOT NULL
        CHECK (salary >= 0),
    city VARCHAR(100) NOT NULL,
    employment_status VARCHAR(20) NOT NULL
        CHECK (
            employment_status IN (
                'ACTIVE',
                'INACTIVE',
                'ON_LEAVE'
            )
        ),
    joining_date DATE NOT NULL,
    performance_score NUMERIC(4, 2)
        CHECK (
            performance_score IS NULL OR
            performance_score BETWEEN 0 AND 100
        )
);

CREATE TABLE IF NOT EXISTS employee_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL
        REFERENCES employees(employee_id),
    transaction_type VARCHAR(30) NOT NULL
        CHECK (
            transaction_type IN (
                'SALARY_REVISION',
                'BONUS',
                'TRANSFER'
            )
        ),
    transaction_amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- 2. SAMPLE DATA
-- ============================================================================

INSERT INTO departments (
    department_name,
    location,
    annual_budget
)
VALUES
    ('Engineering', 'Bengaluru', 5000000),
    ('Security', 'Lucknow', 2500000),
    ('Research', 'Delhi', 4000000),
    ('Operations', 'Mumbai', 3000000),
    ('Analytics', 'Pune', 2000000)
ON CONFLICT (department_name) DO NOTHING;

-- Generate 100,000 employees with reproducible distribution.
INSERT INTO employees (
    employee_name,
    email,
    department_id,
    salary,
    city,
    employment_status,
    joining_date,
    performance_score
)
SELECT
    'Employee_' || generated.employee_number,
    'employee' || generated.employee_number || '@example.org',
    1 + (generated.employee_number % 5),
    25000 + (generated.employee_number % 50) * 2000,
    CASE generated.employee_number % 5
        WHEN 0 THEN 'Lucknow'
        WHEN 1 THEN 'Delhi'
        WHEN 2 THEN 'Mumbai'
        WHEN 3 THEN 'Pune'
        ELSE 'Bengaluru'
    END,
    CASE
        WHEN generated.employee_number % 10 = 0
            THEN 'INACTIVE'
        WHEN generated.employee_number % 15 = 0
            THEN 'ON_LEAVE'
        ELSE 'ACTIVE'
    END,
    DATE '2020-01-01' +
        (generated.employee_number % 2000)::INTEGER,
    (generated.employee_number % 101)::NUMERIC(4, 2)
FROM generate_series(1, 100000) AS generated(employee_number)
ON CONFLICT (email) DO NOTHING;

INSERT INTO employee_transactions (
    employee_id,
    transaction_type,
    transaction_amount
)
SELECT
    employee_id,
    CASE
        WHEN employee_id % 3 = 0 THEN 'BONUS'
        WHEN employee_id % 3 = 1 THEN 'SALARY_REVISION'
        ELSE 'TRANSFER'
    END,
    1000 + (employee_id % 10000)
FROM employees
WHERE employee_id % 10 = 0
ON CONFLICT DO NOTHING;

-- ============================================================================
-- 3. INDEX DESIGN
-- ============================================================================

-- Single-column B-tree index.
CREATE INDEX IF NOT EXISTS idx_employees_department
ON employees(department_id);

-- Selective range predicates.
CREATE INDEX IF NOT EXISTS idx_employees_salary
ON employees(salary);

-- Composite index.
CREATE INDEX IF NOT EXISTS idx_employees_department_salary
ON employees(department_id, salary);

-- Composite index designed for filtering and covering selected columns.
CREATE INDEX IF NOT EXISTS idx_employees_status_city
ON employees(employment_status, city);

-- Covering index for index-only access.
CREATE INDEX IF NOT EXISTS idx_employees_department_covering
ON employees(department_id)
INCLUDE (employee_name, salary);

-- Partial index for frequently queried active employees.
CREATE INDEX IF NOT EXISTS idx_employees_active_salary
ON employees(salary)
WHERE employment_status = 'ACTIVE';

-- Foreign-key access and transaction retrieval.
CREATE INDEX IF NOT EXISTS idx_transactions_employee
ON employee_transactions(employee_id, created_at DESC);

-- ============================================================================
-- 4. STATISTICS COLLECTION
-- ============================================================================

ANALYZE departments;
ANALYZE employees;
ANALYZE employee_transactions;

-- Inspect relation-level statistics.
SELECT
    schemaname,
    relname,
    n_live_tup,
    n_dead_tup,
    last_analyze,
    last_autoanalyze
FROM pg_stat_user_tables
WHERE schemaname = 'explain_lab'
ORDER BY relname;

-- Inspect column distribution statistics.
SELECT
    attname,
    null_frac,
    n_distinct,
    most_common_vals,
    most_common_freqs
FROM pg_stats
WHERE schemaname = 'explain_lab'
  AND tablename = 'employees'
  AND attname IN (
      'department_id',
      'salary',
      'city',
      'employment_status'
  );

-- ============================================================================
-- 5. BASIC EXPLAIN
-- ============================================================================

-- Displays the estimated execution strategy without running the query.
EXPLAIN
SELECT employee_id, employee_name
FROM employees
WHERE department_id = 2;

-- More detailed plan information.
EXPLAIN (VERBOSE, COSTS, SETTINGS)
SELECT employee_id, employee_name
FROM employees
WHERE department_id = 2;

-- ============================================================================
-- 6. SEQUENTIAL SCAN
-- ============================================================================

-- A query retrieving most of the table may favor sequential access.
EXPLAIN (ANALYZE, BUFFERS, VERBOSE, SETTINGS)
SELECT *
FROM employees;

-- A sequential scan is not inherently a performance failure.
-- Its suitability depends on selectivity, relation size and access costs.

-- ============================================================================
-- 7. INDEX SCAN
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT employee_id, employee_name, salary
FROM employees
WHERE salary = 65000;

-- ============================================================================
-- 8. INDEX-ONLY SCAN
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT department_id, employee_name, salary
FROM employees
WHERE department_id = 2;

-- Index-only scans depend on index coverage and visibility-map information.
-- Heap Fetches indicates tuples that still required heap visibility checks.

VACUUM (ANALYZE) employees;

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT department_id, employee_name, salary
FROM employees
WHERE department_id = 2;

-- ============================================================================
-- 9. BITMAP INDEX AND BITMAP HEAP SCANS
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT employee_id, employee_name
FROM employees
WHERE salary BETWEEN 50000 AND 90000;

-- PostgreSQL may combine multiple indexes through BitmapAnd or BitmapOr.
EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT employee_id, employee_name
FROM employees
WHERE department_id = 2
   OR salary BETWEEN 70000 AND 90000;

-- ============================================================================
-- 10. COMPOSITE INDEX
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS)
SELECT employee_id, employee_name, salary
FROM employees
WHERE department_id = 2
  AND salary BETWEEN 50000 AND 100000;

-- Column order matters for multicolumn B-tree indexes.
-- The leading department_id column supports department-based filtering.

-- ============================================================================
-- 11. PARTIAL INDEX
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS)
SELECT employee_id, salary
FROM employees
WHERE employment_status = 'ACTIVE'
  AND salary > 100000;

-- ============================================================================
-- 12. JOIN ALGORITHMS
-- ============================================================================

-- Nested Loop, Hash Join or Merge Join may be selected according to cost.
EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT
    e.employee_id,
    e.employee_name,
    d.department_name
FROM employees AS e
JOIN departments AS d
    ON e.department_id = d.department_id
WHERE e.employee_id <= 100;

-- Hash-oriented join workload.
EXPLAIN (ANALYZE, BUFFERS)
SELECT
    d.department_name,
    COUNT(e.employee_id) AS employee_count
FROM departments AS d
JOIN employees AS e
    ON e.department_id = d.department_id
GROUP BY d.department_name;

-- ============================================================================
-- 13. SORT AND AGGREGATION
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT
    department_id,
    AVG(salary) AS average_salary,
    MAX(salary) AS maximum_salary,
    COUNT(*) AS employee_count
FROM employees
GROUP BY department_id
ORDER BY average_salary DESC;

-- ============================================================================
-- 14. CTE EXECUTION PLAN
-- ============================================================================

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
WITH department_salary AS (
    SELECT
        department_id,
        AVG(salary) AS average_salary
    FROM employees
    GROUP BY department_id
)
SELECT
    d.department_name,
    ds.average_salary
FROM department_salary AS ds
JOIN departments AS d
    ON d.department_id = ds.department_id
WHERE ds.average_salary > 50000;

-- ============================================================================
-- 15. ESTIMATED VERSUS ACTUAL CARDINALITY
-- ============================================================================

EXPLAIN (ANALYZE, VERBOSE)
SELECT *
FROM employees
WHERE city = 'Lucknow'
  AND salary > 90000;

-- A significant difference between estimated and actual rows can indicate:
-- 1. Outdated statistics.
-- 2. Correlated columns.
-- 3. Skewed data distributions.
-- 4. Incorrect selectivity assumptions.
-- 5. Parameter-sensitive query behavior.

-- Extended statistics can help with correlated predicates.
CREATE STATISTICS IF NOT EXISTS employees_city_status_stats
    (dependencies, mcv)
ON city, employment_status
FROM employees;

ANALYZE employees;

EXPLAIN (ANALYZE, VERBOSE)
SELECT *
FROM employees
WHERE city = 'Lucknow'
  AND employment_status = 'ACTIVE';

-- ============================================================================
-- 16. PLANNER COST PARAMETERS
-- ============================================================================

SELECT
    name,
    setting,
    unit,
    source
FROM pg_settings
WHERE name IN (
    'seq_page_cost',
    'random_page_cost',
    'cpu_tuple_cost',
    'cpu_index_tuple_cost',
    'cpu_operator_cost',
    'effective_cache_size',
    'work_mem',
    'enable_seqscan',
    'enable_indexscan',
    'enable_bitmapscan'
)
ORDER BY name;

-- Cost parameters are relative planner units, not milliseconds.
-- effective_cache_size estimates cache availability; it does not allocate memory.

-- ============================================================================
-- 17. DIAGNOSTIC PLAN COMPARISON
-- ============================================================================

CREATE OR REPLACE VIEW employee_department_summary AS
SELECT
    department_id,
    COUNT(*) AS employee_count,
    AVG(salary) AS average_salary,
    MIN(salary) AS minimum_salary,
    MAX(salary) AS maximum_salary
FROM employees
GROUP BY department_id;

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
SELECT *
FROM employee_department_summary
WHERE department_id = 2;

