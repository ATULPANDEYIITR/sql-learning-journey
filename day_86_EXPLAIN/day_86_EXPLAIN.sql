-- ============================================================================
-- 19. PLAN REPORTING FUNCTION
-- ============================================================================

CREATE OR REPLACE FUNCTION explain_lab.relation_statistics(
    p_relation REGCLASS
)
RETURNS TABLE (
    relation_name TEXT,
    estimated_rows REAL,
    estimated_pages BIGINT,
    average_width INTEGER
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        c.relname::TEXT,
        c.reltuples,
        c.relpages::BIGINT,
        COALESCE(
            (
                SELECT AVG(a.attavgwidth)::INTEGER
                FROM pg_attribute AS a
                WHERE a.attrelid = c.oid
                  AND a.attnum > 0
                  AND NOT a.attisdropped
            ),
            0
        )
    FROM pg_class AS c
    WHERE c.oid = p_relation;
$$;

SELECT *
FROM explain_lab.relation_statistics(
    'explain_lab.employees'::REGCLASS
);

-- ============================================================================
-- 20. QUERY WORKLOAD REPORT
-- ============================================================================

SELECT
    e.department_id,
    d.department_name,
    COUNT(*) AS total_employees,
    COUNT(*) FILTER (
        WHERE e.employment_status = 'ACTIVE'
    ) AS active_employees,
    ROUND(AVG(e.salary), 2) AS average_salary
FROM employees AS e
JOIN departments AS d
    ON d.department_id = e.department_id
GROUP BY
    e.department_id,
    d.department_name
ORDER BY total_employees DESC;

-- ============================================================================
-- 21. EXPLAIN ANALYZE SAFETY
-- ============================================================================

-- EXPLAIN ANALYZE executes the statement being explained.
-- Avoid running it blindly on production data modifications.
--
-- Demonstration of safe transactional execution:

BEGIN;

EXPLAIN (ANALYZE, BUFFERS, VERBOSE)
UPDATE employees
SET salary = salary + 100
WHERE employee_id = 1;

ROLLBACK;

-- ROLLBACK reverses transactional table modifications.
-- External side effects, sequences and certain nontransactional operations
-- may not be reversed. Never use this technique as a universal safety guarantee.

-- ============================================================================
-- 22. PERFORMANCE OBSERVATION
-- ============================================================================

SELECT
    schemaname,
    relname,
    seq_scan,
    seq_tup_read,
    idx_scan,
    idx_tup_fetch,
    n_live_tup,
    n_dead_tup
FROM pg_stat_user_tables
WHERE schemaname = 'explain_lab'
ORDER BY seq_tup_read DESC;

-- These statistics are cumulative monitoring counters, not an individual
-- query execution plan. Interpret them with workload and reset history.

-- ============================================================================
-- 23. FINAL VALIDATION
-- ============================================================================

DO $$
DECLARE
    employee_count BIGINT;
    department_count BIGINT;
BEGIN
    SELECT COUNT(*)
    INTO employee_count
    FROM explain_lab.employees;

    SELECT COUNT(*)
    INTO department_count
    FROM explain_lab.departments;

    IF employee_count < 1 THEN
        RAISE EXCEPTION 'Employee dataset is empty.';
    END IF;

    IF department_count < 1 THEN
        RAISE EXCEPTION 'Department dataset is empty.';
    END IF;

    RAISE NOTICE
        'Validation successful: % employees, % departments.',
        employee_count,
        department_count;
END;
$$;

COMMIT;

