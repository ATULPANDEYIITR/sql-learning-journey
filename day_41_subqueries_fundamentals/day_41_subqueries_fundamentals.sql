-- A scalar subquery returns one value.
-- AVG() guarantees one aggregate result for a non-empty relation.
SELECT
    employee_name,
    salary,
    (
        SELECT AVG(salary)
        FROM employees
    ) AS company_average_salary
FROM employees
WHERE salary > (
    SELECT AVG(salary)
    FROM employees
)
ORDER BY salary DESC;

-- A scalar subquery can calculate a threshold used by the outer query.
SELECT
    employee_name,
    salary
FROM employees
WHERE salary = (
    SELECT MAX(salary)
    FROM employees
);

-- A single-row subquery identifies one department.
-- department_name is UNIQUE, so the equality predicate is safe.
SELECT
    employee_name,
    salary
FROM employees
WHERE department_id = (
    SELECT department_id
    FROM departments
    WHERE department_name = 'Security'
)
ORDER BY salary DESC;

-- A multi-row subquery produces several department IDs.
-- IN is appropriate because the outer row may match any returned value.
SELECT
    employee_name,
    department_id,
    salary
FROM employees
WHERE department_id IN (
    SELECT department_id
    FROM departments
    WHERE department_name IN (
        'Engineering',
        'Security',
        'Research'
    )
)
ORDER BY department_id, salary DESC;

-- EXISTS tests whether at least one matching assignment exists.
-- SELECT 1 is conventional because the actual inner value is irrelevant.
SELECT
    e.employee_id,
    e.employee_name
FROM employees AS e
WHERE EXISTS (
    SELECT 1
    FROM employee_projects AS ep
    WHERE ep.employee_id = e.employee_id
      AND ep.allocated_hours >= 180
)
ORDER BY e.employee_id;

-- NOT EXISTS identifies departments without any project.
-- It avoids the NULL-sensitive behavior that can occur with NOT IN.
SELECT
    d.department_id,
    d.department_name
FROM departments AS d
WHERE NOT EXISTS (
    SELECT 1
    FROM projects AS p
    WHERE p.department_id = d.department_id
)
ORDER BY d.department_id;

-- Correlated subquery:
-- the inner query references the current outer employee's department.
SELECT
    e.employee_name,
    e.department_id,
    e.salary
FROM employees AS e
WHERE e.salary > (
    SELECT AVG(other.salary)
    FROM employees AS other
    WHERE other.department_id = e.department_id
)
ORDER BY e.department_id, e.salary DESC;

-- Scalar subquery in the SELECT list.
-- Every employee row receives its own department average.
SELECT
    e.employee_name,
    e.salary,
    (
        SELECT AVG(other.salary)
        FROM employees AS other
        WHERE other.department_id = e.department_id
    ) AS department_average
FROM employees AS e
ORDER BY e.department_id, e.salary DESC;

-- Table subquery / derived table in FROM.
-- The inner query produces a relational result that the outer query filters.
SELECT
    department_name,
    employee_count,
    average_salary
FROM (
    SELECT
        d.department_id,
        d.department_name,
        COUNT(e.employee_id) AS employee_count,
        ROUND(AVG(e.salary), 2) AS average_salary
    FROM departments AS d
    LEFT JOIN employees AS e
        ON e.department_id = d.department_id
    GROUP BY
        d.department_id,
        d.department_name
) AS department_metrics
WHERE employee_count >= 2
ORDER BY average_salary DESC;

-- Nested subqueries:
-- the innermost query finds Engineering;
-- the next query calculates its average;
-- the outer query compares every employee against that value.
SELECT
    employee_name,
    salary
FROM employees
WHERE salary > (
    SELECT AVG(salary)
    FROM employees
    WHERE department_id = (
        SELECT department_id
        FROM departments
        WHERE department_name = 'Engineering'
    )
)
ORDER BY salary DESC;

-- PostgreSQL supports ANY.
-- The employee salary must equal at least one Engineering salary.
SELECT
    employee_name,
    salary
FROM employees
WHERE salary = ANY (
    SELECT salary
    FROM employees
    WHERE department_id = (
        SELECT department_id
        FROM departments
        WHERE department_name = 'Engineering'
    )
)
ORDER BY salary;

-- PostgreSQL supports ALL.
-- The employee salary must exceed every Finance salary.
SELECT
    employee_name,
    salary
FROM employees
WHERE salary > ALL (
    SELECT salary
    FROM employees
    WHERE department_id = (
        SELECT department_id
        FROM departments
        WHERE department_name = 'Finance'
    )
)
ORDER BY salary DESC;

-- Multi-row subquery used with a quantified comparison.
-- This identifies employees whose salary exceeds at least one Finance salary.
SELECT
    employee_name,
    salary
FROM employees
WHERE salary > ANY (
    SELECT salary
    FROM employees
    WHERE department_id = (
        SELECT department_id
        FROM departments
        WHERE department_name = 'Finance'
    )
)
ORDER BY salary DESC;

-- Derived table with an additional aggregate layer.
-- The inner query establishes project totals by department.
-- The outer query evaluates those derived totals.
SELECT
    department_name,
    project_count,
    total_project_budget
FROM (
    SELECT
        d.department_name,
        COUNT(p.project_id) AS project_count,
        COALESCE(SUM(p.budget), 0) AS total_project_budget
    FROM departments AS d
    LEFT JOIN projects AS p
        ON p.department_id = d.department_id
    GROUP BY
        d.department_id,
        d.department_name
) AS project_metrics
WHERE total_project_budget > 500000
ORDER BY total_project_budget DESC;

-- Correlated EXISTS combined with a correlated scalar subquery.
-- A department qualifies only when:
--   1. it has an employee above its own average salary, and
--   2. it owns at least one project.
SELECT
    d.department_name
FROM departments AS d
WHERE EXISTS (
    SELECT 1
    FROM employees AS e
    WHERE e.department_id = d.department_id
      AND e.salary > (
          SELECT AVG(e2.salary)
          FROM employees AS e2
          WHERE e2.department_id = d.department_id
      )
)
AND EXISTS (
    SELECT 1
    FROM projects AS p
    WHERE p.department_id = d.department_id
)
ORDER BY d.department_name;

-- Subquery in INSERT.
-- This creates a reporting table from departments whose payroll exceeds
-- the specified threshold.
DROP TABLE IF EXISTS high_payroll_department_report;

CREATE TABLE high_payroll_department_report (
    department_id INTEGER PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL,
    payroll NUMERIC(14, 2) NOT NULL,
    employee_count BIGINT NOT NULL
);

INSERT INTO high_payroll_department_report (
    department_id,
    department_name,
    payroll,
    employee_count
)
SELECT
    d.department_id,
    d.department_name,
    payroll_metrics.payroll,
    payroll_metrics.employee_count
FROM departments AS d
JOIN (
    SELECT
        department_id,
        SUM(salary) AS payroll,
        COUNT(*) AS employee_count
    FROM employees
    GROUP BY department_id
) AS payroll_metrics
    ON payroll_metrics.department_id = d.department_id
WHERE payroll_metrics.payroll > 200000;

SELECT *
FROM high_payroll_department_report
ORDER BY payroll DESC;

-- Subquery in UPDATE.
-- This statement is executed in a transaction and rolled back so the
-- instructional seed data remains unchanged.
BEGIN;

UPDATE projects
SET budget = budget * 1.05
WHERE department_id IN (
    SELECT department_id
    FROM employees
    GROUP BY department_id
    HAVING SUM(salary) > 200000
);

SELECT
    project_name,
    budget
FROM projects
