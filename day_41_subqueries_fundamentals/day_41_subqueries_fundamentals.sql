-- PostgreSQL-compatible SQL
-- Subqueries Fundamentals
-- Scalar, single-row, multi-row, correlated, and table subqueries

DROP TABLE IF EXISTS employee_projects;
DROP TABLE IF EXISTS projects;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS departments;

CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE employees (
    employee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(100) NOT NULL,
    department_id INTEGER NOT NULL,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary > 0),
    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES departments (department_id)
);

CREATE TABLE projects (
    project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(150) NOT NULL UNIQUE,
    department_id INTEGER NOT NULL,
    budget NUMERIC(14, 2) NOT NULL CHECK (budget > 0),
    CONSTRAINT fk_project_department
        FOREIGN KEY (department_id)
        REFERENCES departments (department_id)
);

CREATE TABLE employee_projects (
    employee_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    allocated_hours NUMERIC(8, 2) NOT NULL CHECK (allocated_hours >= 0),
    PRIMARY KEY (employee_id, project_id),
    CONSTRAINT fk_assignment_employee
        FOREIGN KEY (employee_id)
        REFERENCES employees (employee_id),
    CONSTRAINT fk_assignment_project
        FOREIGN KEY (project_id)
        REFERENCES projects (project_id)
);

CREATE INDEX idx_employees_department
    ON employees (department_id);

CREATE INDEX idx_employees_salary
    ON employees (salary);

CREATE INDEX idx_projects_department
    ON projects (department_id);

CREATE INDEX idx_employee_projects_employee
    ON employee_projects (employee_id);

CREATE INDEX idx_employee_projects_project
    ON employee_projects (project_id);

