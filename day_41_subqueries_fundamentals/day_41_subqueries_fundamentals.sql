-- NULL-sensitive comparison.
-- The result of NOT IN can become UNKNOWN when the subquery returns NULL.
-- EXISTS / NOT EXISTS is usually preferable when nullable data is possible.
SELECT
    5 IN (1, 2, NULL) AS in_with_null,
    5 NOT IN (1, 2, NULL) AS not_in_with_null;

-- A NOT EXISTS formulation does not suffer from the same NULL-list issue.
SELECT
    NOT EXISTS (
        SELECT 1
        FROM (
            VALUES (1), (2), (NULL)
        ) AS values_table(value)
        WHERE values_table.value = 5
    ) AS safe_nonexistence_test;

-- A CTE is not itself a subquery category, but it provides a named
-- relational result that can be compared with an equivalent derived-table
-- approach. This makes the boundary between table expressions and nested
-- query logic explicit.
WITH department_metrics AS (
    SELECT
        d.department_id,
        d.department_name,
        COUNT(e.employee_id) AS employee_count,
        AVG(e.salary) AS average_salary
    FROM departments AS d
    LEFT JOIN employees AS e
        ON e.department_id = d.department_id
    GROUP BY
        d.department_id,
        d.department_name
)
SELECT
    department_name,
    employee_count,
    ROUND(average_salary, 2) AS average_salary
FROM department_metrics
WHERE average_salary > (
    SELECT AVG(average_salary)
    FROM department_metrics
    WHERE employee_count > 0
)
ORDER BY average_salary DESC;

-- Query-plan inspection.
-- PostgreSQL's planner may transform a subquery internally, so SQL syntax
-- alone does not establish runtime performance.
EXPLAIN
SELECT
    employee_name,
    salary
FROM employees
WHERE salary > (
    SELECT AVG(salary)
    FROM employees
);

-- Transactional validation of database-enforced constraints.
-- The invalid salary violates CHECK (salary > 0), and the savepoint lets
-- the transaction continue after the expected failure.
BEGIN;

SAVEPOINT invalid_employee_test;

DO $$
BEGIN
    BEGIN
        INSERT INTO employees (
            employee_name,
            department_id,
            salary
        )
        VALUES (
            'Invalid Employee',
            10,
            -5000
        );
    EXCEPTION
        WHEN check_violation THEN
            RAISE NOTICE
                'Invalid salary rejected by database CHECK constraint.';
    END;
END
$$;

ROLLBACK TO SAVEPOINT invalid_employee_test;
RELEASE SAVEPOINT invalid_employee_test;
ROLLBACK;

