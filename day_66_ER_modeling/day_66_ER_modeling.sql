CREATE TABLE IF NOT EXISTS department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_code VARCHAR(15) NOT NULL,
    department_name VARCHAR(120) NOT NULL,
    building VARCHAR(100),
    established_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_department
        PRIMARY KEY (department_id),

    CONSTRAINT uq_department_code
        UNIQUE (department_code),

    CONSTRAINT uq_department_name
        UNIQUE (department_name),

    CONSTRAINT chk_department_code
        CHECK (department_code ~ '^[A-Z0-9_-]+$')
);


CREATE TABLE IF NOT EXISTS student (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_id BIGINT NOT NULL,
    enrollment_number VARCHAR(25) NOT NULL,
    student_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    date_of_birth DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_student
        PRIMARY KEY (student_id),

    CONSTRAINT uq_student_enrollment_number
        UNIQUE (enrollment_number),

    CONSTRAINT uq_student_email
        UNIQUE (email),

    CONSTRAINT fk_student_department
        FOREIGN KEY (department_id)
        REFERENCES department(department_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_student_email
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),

    CONSTRAINT chk_student_dob
        CHECK (
            date_of_birth IS NULL
            OR date_of_birth < CURRENT_DATE
        )
);


CREATE TABLE IF NOT EXISTS instructor (
    instructor_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_id BIGINT NOT NULL,
    employee_number VARCHAR(25) NOT NULL,
    instructor_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    salary NUMERIC(12, 2),
    joining_date DATE NOT NULL DEFAULT CURRENT_DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_instructor
        PRIMARY KEY (instructor_id),

    CONSTRAINT uq_instructor_employee_number
        UNIQUE (employee_number),

    CONSTRAINT uq_instructor_email
        UNIQUE (email),

    CONSTRAINT fk_instructor_department
        FOREIGN KEY (department_id)
        REFERENCES department(department_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_instructor_salary
        CHECK (salary IS NULL OR salary >= 0)
);


CREATE TABLE IF NOT EXISTS course (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_id BIGINT NOT NULL,
    instructor_id BIGINT NOT NULL,
    course_code VARCHAR(20) NOT NULL,
    course_name VARCHAR(150) NOT NULL,
    credits INTEGER NOT NULL,
    semester VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_course
        PRIMARY KEY (course_id),

    CONSTRAINT uq_course_code
        UNIQUE (course_code),

    CONSTRAINT fk_course_department
        FOREIGN KEY (department_id)
        REFERENCES department(department_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_course_instructor
        FOREIGN KEY (instructor_id)
        REFERENCES instructor(instructor_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_course_credits
        CHECK (credits BETWEEN 1 AND 10),

    CONSTRAINT chk_course_semester
        CHECK (
            semester IN (
                'SPRING',
                'SUMMER',
                'AUTUMN',
                'WINTER'
            )
        )
);


-- ===========================================================================
-- 2. ASSOCIATIVE ENTITY: ENROLLMENT
-- ===========================================================================

/*
Student and Course have an M:N relationship.

One student may enroll in many courses.
One course may contain many students.

The Enrollment entity resolves this relationship.

The composite primary key prevents duplicate enrollment
of the same student in the same course.
*/

CREATE TABLE IF NOT EXISTS enrollment (
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    grade VARCHAR(2),
    status VARCHAR(20) NOT NULL DEFAULT 'ENROLLED',

    CONSTRAINT pk_enrollment
        PRIMARY KEY (student_id, course_id),

    CONSTRAINT fk_enrollment_student
        FOREIGN KEY (student_id)
        REFERENCES student(student_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_enrollment_course
        FOREIGN KEY (course_id)
        REFERENCES course(course_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_enrollment_grade
        CHECK (
            grade IS NULL
            OR grade IN (
                'A+',
                'A',
                'B+',
                'B',
                'C',
                'D',
                'F',
                'I'
            )
        ),

    CONSTRAINT chk_enrollment_status
        CHECK (
            status IN (
                'ENROLLED',
                'COMPLETED',
                'WITHDRAWN'
            )
        )
);


