-- 10. AGGREGATION AND EVALUATION QUERIES
-- ===========================================================================

-- Query A: Retrieve all entities participating in the M:N relationship.

SELECT *
FROM student_course_details
ORDER BY student_id, course_id;


-- Query B: Department-level relationship aggregation.

SELECT *
FROM department_statistics
ORDER BY department_id;


-- Query C: Identify students who are not enrolled in any course.
-- Student participation in Enrollment is partial.

SELECT
    s.student_id,
    s.student_name
FROM student s
LEFT JOIN enrollment e
    ON e.student_id = s.student_id
WHERE e.student_id IS NULL;


-- Query D: Identify courses without enrollments.
-- Useful for checking the total-participation business rule.

SELECT
    c.course_id,
    c.course_name
FROM course c
LEFT JOIN enrollment e
    ON e.course_id = c.course_id
WHERE e.course_id IS NULL;


-- Query E: Calculate enrollment count and average completed credits.

SELECT
    c.course_id,
    c.course_name,
    COUNT(e.student_id) AS enrollment_count,
    COUNT(e.grade) AS graded_enrollment_count
FROM course c
LEFT JOIN enrollment e
    ON e.course_id = c.course_id
GROUP BY
    c.course_id,
    c.course_name
ORDER BY enrollment_count DESC;


-- Query F: Identify relationships and their cardinalities.

SELECT *
FROM er_relationship_catalog
ORDER BY relationship_name;


-- Query G: Run participation and referential integrity checks.

SELECT *
FROM validate_er_relationships();


