CREATE OR REPLACE VIEW er_relationship_catalog AS

SELECT
    'Department' AS entity_one,
    'Student' AS entity_two,
    'DepartmentStudent' AS relationship_name,
    '1:N' AS cardinality,
    'TOTAL' AS entity_two_participation,
    'PARTIAL' AS entity_one_participation,
    'student.department_id' AS foreign_key_location

UNION ALL

SELECT
    'Department',
    'Instructor',
    'DepartmentInstructor',
    '1:N',
    'TOTAL',
    'TOTAL',
    'instructor.department_id'

UNION ALL

SELECT
    'Department',
    'Course',
    'DepartmentCourse',
    '1:N',
    'TOTAL',
    'PARTIAL',
    'course.department_id'

UNION ALL

SELECT
    'Instructor',
    'Course',
    'InstructorCourse',
    '1:N',
    'TOTAL',
    'PARTIAL',
    'course.instructor_id'

UNION ALL

SELECT
    'Student',
    'Course',
    'Enrollment',
    'M:N',
    'PARTIAL',
    'PARTIAL',
    'enrollment.student_id, enrollment.course_id';


-- ===========================================================================
-- 7. RELATIONSHIP AND ENTITY REPORTING VIEWS
-- ===========================================================================

CREATE OR REPLACE VIEW student_course_details AS
SELECT
    s.student_id,
    s.enrollment_number,
    s.student_name,
    d.department_name,
    c.course_id,
    c.course_code,
    c.course_name,
    e.enrollment_date,
    e.grade,
    e.status
FROM student s
JOIN department d
    ON d.department_id = s.department_id
JOIN enrollment e
    ON e.student_id = s.student_id
JOIN course c
    ON c.course_id = e.course_id;


CREATE OR REPLACE VIEW department_statistics AS
SELECT
    d.department_id,
    d.department_code,
    d.department_name,
    COUNT(DISTINCT s.student_id) AS student_count,
    COUNT(DISTINCT i.instructor_id) AS instructor_count,
    COUNT(DISTINCT c.course_id) AS course_count
FROM department d
LEFT JOIN student s
    ON s.department_id = d.department_id
LEFT JOIN instructor i
    ON i.department_id = d.department_id
LEFT JOIN course c
    ON c.department_id = d.department_id
GROUP BY
    d.department_id,
    d.department_code,
    d.department_name;


-- ===========================================================================
-- 8. ENTITY AND RELATIONSHIP VALIDATION FUNCTION
-- ===========================================================================

CREATE OR REPLACE FUNCTION validate_er_relationships()
RETURNS TABLE (
    relationship_name TEXT,
    validation_status TEXT,
    violation_count BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN

    RETURN QUERY
    SELECT
        'Department-Instructor'::TEXT,
        CASE
            WHEN COUNT(*) = 0 THEN 'PASS'
            ELSE 'FAIL'
        END,
        COUNT(*)
    FROM department d
    WHERE NOT EXISTS (
        SELECT 1
        FROM instructor i
        WHERE i.department_id = d.department_id
    );

    RETURN QUERY
    SELECT
        'Course-Enrollment'::TEXT,
        CASE
            WHEN COUNT(*) = 0 THEN 'PASS'
            ELSE 'FAIL'
        END,
        COUNT(*)
    FROM course c
    WHERE NOT EXISTS (
        SELECT 1
        FROM enrollment e
        WHERE e.course_id = c.course_id
    );

    RETURN QUERY
    SELECT
        'Student-Department'::TEXT,
        CASE
            WHEN COUNT(*) = 0 THEN 'PASS'
            ELSE 'FAIL'
        END,
        COUNT(*)
    FROM student s
    LEFT JOIN department d
        ON d.department_id = s.department_id
    WHERE d.department_id IS NULL;

END;
$$;


-- ===========================================================================
-- 9. COURSE ENROLLMENT PROCEDURE
-- ===========================================================================

CREATE OR REPLACE PROCEDURE enroll_student(
    p_student_id BIGINT,
    p_course_id BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM student
        WHERE student_id = p_student_id
          AND active = TRUE
    ) THEN
        RAISE EXCEPTION
            'Student % is not active or does not exist',
            p_student_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM course
        WHERE course_id = p_course_id
          AND active = TRUE
    ) THEN
        RAISE EXCEPTION
            'Course % is not active or does not exist',
            p_course_id;
    END IF;

    INSERT INTO enrollment (
        student_id,
        course_id,
        enrollment_date,
        status
    )
    VALUES (
        p_student_id,
        p_course_id,
        CURRENT_DATE,
        'ENROLLED'
    );

    RAISE NOTICE
        'Student % enrolled in course %',
        p_student_id,
        p_course_id;

EXCEPTION
    WHEN unique_violation THEN
        RAISE EXCEPTION
            'Student % is already enrolled in course %',
            p_student_id,
            p_course_id;
END;
$$;


