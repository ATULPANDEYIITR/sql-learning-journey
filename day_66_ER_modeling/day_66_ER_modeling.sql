-- ===========================================================================
-- 5. PARTICIPATION VALIDATION
-- ===========================================================================

/*
A foreign key enforces referential integrity.

NOT NULL on a foreign key enforces mandatory participation
for the referencing entity.

A foreign key alone does not ensure that every parent entity
has at least one child.

The following deferred constraint triggers enforce total
participation on selected parent-child relationships.

The checks execute at transaction commit, allowing related
rows to be inserted in the same transaction.
*/

CREATE OR REPLACE FUNCTION check_department_has_instructor()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM department d
        WHERE d.department_id = NEW.department_id
          AND NOT EXISTS (
              SELECT 1
              FROM instructor i
              WHERE i.department_id = d.department_id
          )
    ) THEN
        RAISE EXCEPTION
            'Department % requires at least one instructor',
            NEW.department_id;
    END IF;

    RETURN NULL;
END;
$$;


CREATE OR REPLACE FUNCTION check_course_has_enrollment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    affected_course_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        affected_course_id := OLD.course_id;
    ELSE
        affected_course_id := NEW.course_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM course c
        WHERE c.course_id = affected_course_id
          AND NOT EXISTS (
              SELECT 1
              FROM enrollment e
              WHERE e.course_id = c.course_id
          )
    ) THEN
        RAISE EXCEPTION
            'Course % requires at least one enrollment',
            affected_course_id;
    END IF;

    RETURN NULL;
END;
$$;


CREATE OR REPLACE FUNCTION check_order_of_department_instructor()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF EXISTS (
            SELECT 1
            FROM department d
            WHERE d.department_id = OLD.department_id
              AND NOT EXISTS (
                  SELECT 1
                  FROM instructor i
                  WHERE i.department_id = d.department_id
              )
        ) THEN
            RAISE EXCEPTION
                'Cannot remove the last instructor from department %',
                OLD.department_id;
        END IF;

    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.department_id <> NEW.department_id
           AND NOT EXISTS (
                SELECT 1
                FROM instructor i
                WHERE i.department_id = OLD.department_id
                  AND i.instructor_id <> OLD.instructor_id
           )
        THEN
            RAISE EXCEPTION
                'Cannot remove the last instructor from department %',
                OLD.department_id;
        END IF;
    END IF;

    RETURN NULL;
END;
$$;


/*
The deferred parent check permits creation of a department
and its first instructor within the same transaction.
*/

CREATE OR REPLACE FUNCTION check_department_after_instructor_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    affected_department_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        affected_department_id := OLD.department_id;
    ELSE
        affected_department_id := NEW.department_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM department d
        WHERE d.department_id = affected_department_id
          AND NOT EXISTS (
              SELECT 1
              FROM instructor i
              WHERE i.department_id = d.department_id
          )
    ) THEN
        RAISE EXCEPTION
            'Department % must have an instructor',
            affected_department_id;
    END IF;

    RETURN NULL;
END;
$$;


DROP TRIGGER IF EXISTS trg_department_requires_instructor
    ON instructor;

CREATE CONSTRAINT TRIGGER trg_department_requires_instructor
AFTER INSERT OR UPDATE OR DELETE ON instructor
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION check_department_after_instructor_change();


DROP TRIGGER IF EXISTS trg_department_instructor_delete
    ON instructor;

CREATE TRIGGER trg_department_instructor_delete
AFTER DELETE OR UPDATE ON instructor
FOR EACH ROW
EXECUTE FUNCTION check_order_of_department_instructor();


DROP TRIGGER IF EXISTS trg_course_requires_enrollment
    ON enrollment;

CREATE CONSTRAINT TRIGGER trg_course_requires_enrollment
AFTER INSERT OR UPDATE OR DELETE ON enrollment
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION check_course_has_enrollment();


