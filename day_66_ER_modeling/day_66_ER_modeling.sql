-- 12. TRANSACTIONAL WORKFLOW
-- ===========================================================================

/*
The procedure is executed inside a transaction.

A failed enrollment rolls back without leaving partial records.
*/

DO $$
BEGIN
    BEGIN
        CALL enroll_student(102, 302);

        RAISE NOTICE 'Transactional enrollment succeeded.';

    EXCEPTION
        WHEN OTHERS THEN
            RAISE NOTICE
                'Enrollment transaction failed: %',
                SQLERRM;
    END;
END;
$$;


