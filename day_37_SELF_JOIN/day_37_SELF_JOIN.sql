-- -------------------------------------------------------------------------
-- Immediate employee-manager SELF JOIN
-- -------------------------------------------------------------------------
--
-- INNER JOIN excludes root employees because their manager_id is NULL.
-- Two aliases are essential because employee and manager are two logical
-- roles played by rows in the same physical table.

SELECT
    e.employee_id,
    e.employee_name AS employee,
    e.job_title AS employee_title,
    m.employee_id AS manager_id,
    m.employee_name AS manager,
    m.job_title AS manager_title
FROM employee AS e
JOIN employee AS m
    ON e.manager_id = m.employee_id
ORDER BY e.employee_id;

-- -------------------------------------------------------------------------
-- LEFT SELF JOIN including organization roots
-- -------------------------------------------------------------------------
--
-- LEFT JOIN preserves employees whose manager_id is NULL.

SELECT
    e.employee_id,
    e.employee_name AS employee,
    e.job_title,
    COALESCE(m.employee_name, 'Organization Root') AS manager
FROM employee AS e
LEFT JOIN employee AS m
    ON e.manager_id = m.employee_id
ORDER BY e.employee_id;

