-- -------------------------------------------------------------------------
-- Demonstrate a transaction for a hierarchy change
-- -------------------------------------------------------------------------
--
-- Sana moves from Vikram (4) to Priya (5).
--
-- The foreign key guarantees that manager 5 exists. The self-management
-- CHECK prevents manager_id = employee_id. Application-level cycle
-- detection is still necessary for multi-row hierarchical cycles because
-- ordinary foreign keys do not by themselves prove that the graph is acyclic.

BEGIN;

UPDATE employee
SET manager_id = 5
WHERE employee_id = 8;

-- Verify the resulting immediate relationship before committing.

SELECT
    e.employee_name AS employee,
    m.employee_name AS manager
FROM employee AS e
LEFT JOIN employee AS m
    ON e.manager_id = m.employee_id
WHERE e.employee_id = 8;

COMMIT;

-- -------------------------------------------------------------------------
-- Invalid direct self-management is rejected by the CHECK constraint.
-- This statement is intentionally isolated inside a savepoint so the
-- demonstration does not terminate the remainder of the SQL script.
-- -------------------------------------------------------------------------

BEGIN;

SAVEPOINT invalid_self_manager;

UPDATE employee
SET manager_id = employee_id
WHERE employee_id = 5;

ROLLBACK TO SAVEPOINT invalid_self_manager;

COMMIT;

-- -------------------------------------------------------------------------
-- Invalid manager references are rejected by the foreign key.
-- -------------------------------------------------------------------------

BEGIN;

SAVEPOINT invalid_manager_reference;

UPDATE employee
SET manager_id = 999999
WHERE employee_id = 8;

ROLLBACK TO SAVEPOINT invalid_manager_reference;

COMMIT;

-- -------------------------------------------------------------------------
-- Managers at each hierarchy level
-- -------------------------------------------------------------------------

WITH RECURSIVE hierarchy AS (
    SELECT
        employee_id,
        employee_name,
        manager_id,
        0 AS depth
    FROM employee
    WHERE manager_id IS NULL

    UNION ALL

    SELECT
        e.employee_id,
        e.employee_name,
        e.manager_id,
        h.depth + 1
    FROM employee AS e
    JOIN hierarchy AS h
        ON e.manager_id = h.employee_id
)
SELECT
    depth,
    COUNT(*) AS employee_count
FROM hierarchy
GROUP BY depth
ORDER BY depth;

-- -------------------------------------------------------------------------
-- Employees with at least two levels of management above them
-- -------------------------------------------------------------------------

WITH RECURSIVE hierarchy AS (
    SELECT
        employee_id,
        employee_name,
        manager_id,
        0 AS depth
    FROM employee
    WHERE manager_id IS NULL

    UNION ALL

    SELECT
        e.employee_id,
        e.employee_name,
        e.manager_id,
        h.depth + 1
    FROM employee AS e
    JOIN hierarchy AS h
        ON e.manager_id = h.employee_id
)
SELECT
    employee_id,
    employee_name,
    depth
FROM hierarchy
WHERE depth >= 2
ORDER BY depth, employee_name;

-- -------------------------------------------------------------------------
-- Practical view for repeated employee-manager reporting
-- -------------------------------------------------------------------------

CREATE OR REPLACE VIEW employee_manager_view AS
SELECT
    e.employee_id,
    e.employee_name AS employee_name,
    e.job_title AS employee_title,
    e.department,
    e.annual_salary,
    e.manager_id,
    m.employee_name AS manager_name,
    m.job_title AS manager_title
FROM employee AS e
LEFT JOIN employee AS m
    ON e.manager_id = m.employee_id;

SELECT *
FROM employee_manager_view
ORDER BY employee_id;

-- -------------------------------------------------------------------------
-- Hierarchical integrity checks
-- -------------------------------------------------------------------------
--
-- Missing managers cannot exist because of the foreign key, but this query
-- demonstrates the logical condition that should be monitored in imported
-- or staged data.

SELECT
    e.employee_id,
    e.employee_name,
    e.manager_id
FROM employee AS e
LEFT JOIN employee AS m
    ON e.manager_id = m.employee_id
WHERE e.manager_id IS NOT NULL
  AND m.employee_id IS NULL;

-- Root employees are the rows with no parent.

SELECT
    employee_id,
    employee_name,
    job_title
FROM employee
WHERE manager_id IS NULL
ORDER BY employee_id;

