-- -------------------------------------------------------------------------
-- Employees earning less than their immediate manager
-- -------------------------------------------------------------------------
--
-- The second copy of employee supplies salary information for the manager.

SELECT
    e.employee_name AS employee,
    e.annual_salary AS employee_salary,
    m.employee_name AS manager,
    m.annual_salary AS manager_salary,
    m.annual_salary - e.annual_salary AS salary_gap
FROM employee AS e
JOIN employee AS m
    ON e.manager_id = m.employee_id
WHERE e.annual_salary < m.annual_salary
ORDER BY salary_gap DESC;

-- -------------------------------------------------------------------------
-- Managers with the number of direct reports
-- -------------------------------------------------------------------------

SELECT
    m.employee_id AS manager_id,
    m.employee_name AS manager,
    COUNT(e.employee_id) AS direct_report_count
FROM employee AS m
LEFT JOIN employee AS e
    ON e.manager_id = m.employee_id
GROUP BY
    m.employee_id,
    m.employee_name
HAVING COUNT(e.employee_id) > 0
ORDER BY direct_report_count DESC, manager;

-- -------------------------------------------------------------------------
-- Employees and their management depth
-- -------------------------------------------------------------------------
--
-- Recursive CTEs are used when the requirement is more than an immediate
-- SELF JOIN. The recursive query follows manager_id repeatedly until a root
-- is reached.

WITH RECURSIVE management_chain AS (
    SELECT
        employee_id,
        employee_name,
        manager_id,
        0 AS depth
    FROM employee
    WHERE manager_id IS NULL

    UNION ALL

    SELECT
        child.employee_id,
        child.employee_name,
        child.manager_id,
        parent.depth + 1
    FROM employee AS child
    JOIN management_chain AS parent
        ON child.manager_id = parent.employee_id
)
SELECT
    employee_id,
    employee_name,
    depth
FROM management_chain
ORDER BY depth, employee_id;

-- -------------------------------------------------------------------------
-- Full management path for every employee
-- -------------------------------------------------------------------------
--
-- ARRAY is used to preserve the path from root to employee.

WITH RECURSIVE hierarchy AS (
    SELECT
        employee_id,
        employee_name,
        manager_id,
        0 AS depth,
        ARRAY[employee_name]::TEXT[] AS management_path
    FROM employee
    WHERE manager_id IS NULL

    UNION ALL

    SELECT
        child.employee_id,
        child.employee_name,
        child.manager_id,
        parent.depth + 1,
        parent.management_path || child.employee_name
    FROM employee AS child
    JOIN hierarchy AS parent
        ON child.manager_id = parent.employee_id
)
SELECT
    employee_id,
    employee_name,
    depth,
    array_to_string(management_path, ' -> ') AS management_path
FROM hierarchy
ORDER BY management_path;

