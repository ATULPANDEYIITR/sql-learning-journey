-- PostgreSQL SELF JOIN demonstration:
-- hierarchical employee-manager relationships.
--
-- The key design is:
--
--   employee.manager_id REFERENCES organization.employee(employee_id)
--
-- The employee table therefore references itself. A SELF JOIN gives the
-- same table two logical roles:
--
--   employee = person being reported
--   manager  = person responsible for that employee
--
-- This script is intentionally PostgreSQL-compatible and uses database
-- constraints to protect the hierarchy.

DROP SCHEMA IF EXISTS organization CASCADE;

CREATE SCHEMA organization;

SET search_path TO organization, public;

CREATE TABLE employee (
    employee_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name    TEXT NOT NULL,
    job_title        TEXT NOT NULL,
    manager_id       BIGINT NULL,
    department       TEXT NOT NULL,
    annual_salary    NUMERIC(12, 2) NOT NULL,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT employee_name_not_blank
        CHECK (btrim(employee_name) <> ''),

    CONSTRAINT employee_title_not_blank
        CHECK (btrim(job_title) <> ''),

    CONSTRAINT employee_department_not_blank
        CHECK (btrim(department) <> ''),

    CONSTRAINT employee_salary_nonnegative
        CHECK (annual_salary >= 0),

    CONSTRAINT employee_cannot_manage_self
        CHECK (manager_id IS NULL OR manager_id <> employee_id),

    CONSTRAINT employee_manager_fk
        FOREIGN KEY (manager_id)
        REFERENCES employee(employee_id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- This index makes direct-report lookups efficient:
--
--   WHERE manager_id = ?
--
-- It is the database-level equivalent of maintaining a child lookup
-- structure for the hierarchy.
CREATE INDEX idx_employee_manager_id
    ON employee(manager_id);

CREATE INDEX idx_employee_department_manager
    ON employee(department, manager_id);

